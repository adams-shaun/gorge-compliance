// writeCommit must not delete committed scenarios a run did not regenerate.
// A chunk or an -only run writes one method's result into a class file that
// may hold others; a method whose translation now fails the harness or is
// refused has no replacement scenario at all, and the committed one still
// passes the audit, so it stays.
func TestWriteCommitKeepsScenariosNotRegenerated(t *testing.T) {
	dir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(dir, "single"), 0o755); err != nil {
		t.Fatal(err)
	}
	old := portFile{
		Source: "Mage.Tests/src/test/java/org/mage/test/cards/single/zen/CobraTrapTest.java (XMage, MIT; generated by cmd/xmageport)",
		Scenarios: []portScenario{
			{Name: "test-card", XMage: "CobraTrapTest#testCard"},
			{Name: "test-harness", XMage: "CobraTrapTest#testHarness"},
			{Name: "test-refused", XMage: "CobraTrapTest#testRefused"},
		},
	}
	raw, err := json.MarshalIndent(old, "", " ")
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "single", "CobraTrapTest.json")
	if err := os.WriteFile(path, raw, 0o644); err != nil {
		t.Fatal(err)
	}
	results := []*result{
		{Family: "single", Class: "CobraTrapTest", Method: "testCardNegative", Rel: "cards/single/zen/CobraTrapTest.java",
			Status: "pass", Scenario: &portScenario{Name: "test-card-negative", XMage: "CobraTrapTest#testCardNegative"}},
		{Family: "single", Class: "CobraTrapTest", Method: "testHarness", Rel: "cards/single/zen/CobraTrapTest.java",
			Status: "fail-harness", Scenario: &portScenario{Name: "test-harness", XMage: "CobraTrapTest#testHarness"}},
		{Family: "single", Class: "CobraTrapTest", Method: "testRefused", Rel: "cards/single/zen/CobraTrapTest.java",
			Status: "refused", Code: "some-shape", Detail: "cannot express"},
	}
	if err := writeCommit(dir, results); err != nil {
		t.Fatal(err)
	}
	got, ok := readPortFile(path)
	if !ok {
		t.Fatal("writeCommit did not produce a readable file")
	}
	var names []string
	for _, sc := range got.Scenarios {
		names = append(names, sc.Name)
	}
	want := []string{"test-card", "test-harness", "test-refused", "test-card-negative"}
	if len(names) != len(want) {
		t.Fatalf("scenarios %v, want %v", names, want)
	}
	for i := range want {
		if names[i] != want[i] {
			t.Fatalf("scenarios %v, want %v", names, want)
		}
	}
}

func portNames(t *testing.T, path string) []string {
	t.Helper()
	got, ok := readPortFile(path)
	if !ok {
		t.Fatalf("%s is not a readable port file", path)
	}
	var names []string
	for _, sc := range got.Scenarios {
		names = append(names, sc.Name)
	}
	return names
}

func writeOldPortFile(t *testing.T, dir, name, source string, scs ...portScenario) string {
	t.Helper()
	if err := os.MkdirAll(filepath.Join(dir, "single"), 0o755); err != nil {
		t.Fatal(err)
	}
	raw, err := json.MarshalIndent(portFile{Source: source, Scenarios: scs}, "", " ")
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "single", name)
	if err := os.WriteFile(path, raw, 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

const generatedSource = "Mage.Tests/src/test/java/org/mage/test/cards/single/zen/CobraTrapTest.java (XMage, MIT; generated by cmd/xmageport)"

// A fail-harness method with a known_bug row is written anew, so its old
// scenario must not be kept beside the new one: run twice, the list is the
// same, not one longer.
func TestWriteCommitKnownBugFailHarnessIsNotDuplicated(t *testing.T) {
	dir := t.TempDir()
	old := knownBugs
	knownBugs = map[string]string{"CobraTrapTest#testCard": "some gorge bug"}
	t.Cleanup(func() { knownBugs = old })
	path := writeOldPortFile(t, dir, "CobraTrapTest.json", generatedSource,
		portScenario{Name: "test-card", XMage: "CobraTrapTest#testCard", Why: "old body"})
	mk := func() []*result {
		return []*result{{Family: "single", Class: "CobraTrapTest", Method: "testCard", Rel: "cards/single/zen/CobraTrapTest.java",
			Status: "fail-harness", Scenario: &portScenario{Name: "test-card", XMage: "CobraTrapTest#testCard", Why: "new body"}}}
	}
	for run := 1; run <= 2; run++ {
		if err := writeCommit(dir, mk()); err != nil {
			t.Fatal(err)
		}
		if names := portNames(t, path); len(names) != 1 {
			t.Fatalf("run %d: scenarios %v, want exactly one test-card", run, names)
		}
	}
	got, _ := readPortFile(path)
	if got.Scenarios[0].Why != "new body" || got.Scenarios[0].KnownBug != "some gorge bug" {
		t.Fatalf("kept %+v, want the new known_bug body", got.Scenarios[0])
	}
}

// A class whose only results are refusals has no scenario to write; its old
// scenarios still pass the audit, so they stay. A file that is not generated
// (hand-ported) is never touched.
func TestWriteCommitRefusalKeepsOldScenarioWithoutANewOne(t *testing.T) {
	dir := t.TempDir()
	path := writeOldPortFile(t, dir, "CobraTrapTest.json", generatedSource,
		portScenario{Name: "test-a", XMage: "CobraTrapTest#testA"},
		portScenario{Name: "test-b", XMage: "CobraTrapTest#testB"})
	only := writeOldPortFile(t, dir, "OnlyTest.json", "Mage.Tests/x/OnlyTest.java (generated by cmd/xmageport)",
		portScenario{Name: "test-only", XMage: "OnlyTest#testOnly"})
	hand := writeOldPortFile(t, dir, "HandTest.json", "hand ported",
		portScenario{Name: "test-hand", XMage: "HandTest#testHand"})
	rows := []*result{
		{Family: "single", Class: "CobraTrapTest", Method: "testA", Status: "refused", Code: "some-shape"},
		{Family: "single", Class: "OnlyTest", Method: "testOnly", Status: "fail-expect"},
		{Family: "single", Class: "HandTest", Method: "testHand", Status: "refused", Code: "some-shape"},
	}
	if err := writeCommit(dir, rows); err != nil {
		t.Fatal(err)
	}
	if names := portNames(t, path); len(names) != 2 || names[0] != "test-a" || names[1] != "test-b" {
		t.Fatalf("scenarios %v, want the refused test-a kept beside test-b", names)
	}
	if names := portNames(t, only); len(names) != 1 || names[0] != "test-only" {
		t.Fatalf("scenarios %v, want the fail-expect test-only kept", names)
	}
	if names := portNames(t, hand); len(names) != 1 {
		t.Fatalf("hand-ported file changed: %v", names)
	}
}

// checkCommit is writeCommit's dry run: it must name the committed file a run
// would change (here, a hand-edited generated scenario) and leave it
// byte-identical, so a generated scenario cannot drift from the generator
// output unnoticed.
func TestCheckCommitReportsDriftWithoutWriting(t *testing.T) {
	dir := t.TempDir()
	sc := portScenario{Name: "test-card", XMage: "CobraTrapTest#testCard"}
	f := portFile{Source: generatedSource, Scenarios: []portScenario{sc}}
	path := filepath.Join(dir, "single", "CobraTrapTest.json")
	if err := writePortFile(path, f); err != nil {
		t.Fatal(err)
	}
	mk := func() []*result {
		return []*result{{Family: "single", Class: "CobraTrapTest", Method: "testCard",
			Rel: "cards/single/zen/CobraTrapTest.java", Status: "pass", Scenario: &sc}}
	}
	drift, err := checkCommit(dir, mk())
	if err != nil || len(drift) != 0 {
		t.Fatalf("checkCommit on the generator's own output = %v, %v; want no drift", drift, err)
	}
	edited := f
	edited.Scenarios = []portScenario{{Name: "test-card", XMage: "CobraTrapTest#testCard", Why: "hand added"}}
	if err := writePortFile(path, edited); err != nil {
		t.Fatal(err)
	}
	before, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	drift, err = checkCommit(dir, mk())
	if err != nil || len(drift) != 1 || drift[0] != path {
		t.Fatalf("checkCommit on a hand-edited file = %v, %v; want [%s]", drift, err, path)
	}
	after, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(before, after) {
		t.Fatal("checkCommit rewrote the committed file")
	}
}
