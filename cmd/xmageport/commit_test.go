package main

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

// writeCommit must not delete committed scenarios a run did not regenerate.
// A chunk or an -only run writes one method's result into a class file that
// may hold others; a method whose translation now fails the harness has no
// replacement scenario at all. Only a triaged refusal or fail-expect is a
// deliberate removal.
func TestWriteCommitKeepsScenariosNotRegenerated(t *testing.T) {
	dir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(dir, "single"), 0o755); err != nil {
		t.Fatal(err)
	}
	old := portFile{
		Source: "Mage.Tests/src/test/java/org/mage/test/cards/single/zen/CobraTrapTest.java (XMage, MIT; generated by cmd/xmageport)",
		Scenarios: []portScenario{
			{Name: "test-card", XMage: "CobraTrapTest#testCard"},
			{Name: "test-harness", XMage: "CobraTrapTest#testHarness"},
			{Name: "test-refused", XMage: "CobraTrapTest#testRefused"},
		},
	}
	raw, err := json.MarshalIndent(old, "", " ")
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "single", "CobraTrapTest.json")
	if err := os.WriteFile(path, raw, 0o644); err != nil {
		t.Fatal(err)
	}
	results := []*result{
		{Family: "single", Class: "CobraTrapTest", Method: "testCardNegative", Rel: "cards/single/zen/CobraTrapTest.java",
			Status: "pass", Scenario: &portScenario{Name: "test-card-negative", XMage: "CobraTrapTest#testCardNegative"}},
		{Family: "single", Class: "CobraTrapTest", Method: "testHarness", Rel: "cards/single/zen/CobraTrapTest.java",
			Status: "fail-harness", Scenario: &portScenario{Name: "test-harness", XMage: "CobraTrapTest#testHarness"}},
		{Family: "single", Class: "CobraTrapTest", Method: "testRefused", Rel: "cards/single/zen/CobraTrapTest.java",
			Status: "refused", Code: "some-shape", Detail: "cannot express"},
	}
	if err := writeCommit(dir, results); err != nil {
		t.Fatal(err)
	}
	got, ok := readPortFile(path)
	if !ok {
		t.Fatal("writeCommit did not produce a readable file")
	}
	var names []string
	for _, sc := range got.Scenarios {
		names = append(names, sc.Name)
	}
	want := []string{"test-card", "test-harness", "test-card-negative"}
	if len(names) != len(want) {
		t.Fatalf("scenarios %v, want %v", names, want)
	}
	for i := range want {
		if names[i] != want[i] {
			t.Fatalf("scenarios %v, want %v", names, want)
		}
	}
}
