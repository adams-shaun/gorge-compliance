func pref(p int) string { return fmt.Sprintf("p%d", p) }

// runnerZoneOrder is the order rules' build binds setup refs in.
var runnerZoneOrder = []string{"battlefield", "hand", "graveyard", "library", "exile", "command", "library_top"}

func (t *translator) build() (*portScenario, []*group, *refusal) {
	// Asserts need to be read before lands are dropped (assertPermanentCount
	// without a name keeps every land).
	for _, c := range t.asserts {
		if c.Name == "assertPermanentCount" && len(c.Args) == 2 {
			t.needAll = true
		}
	}
	for _, pc := range t.pendingChecks {
		if pc.c.Name == "assertPermanentCount" && len(pc.c.Args) == 2 {
			t.needAll = true
		}
	}
	sc := &portScenario{Name: kebab(t.m.Name), CR: []string{}, Setup: map[string]*seat{},
		Why: fmt.Sprintf("Generated by cmd/xmageport from XMage %s#%s.", t.jc.Name, t.m.Name)}
	if t.seats() > 2 {
		// absent (0) is the runner's two-seat game, so two-seat bytes keep
		// no players field
		sc.Players = t.seats()
	}
	for p := 0; p < t.seats(); p++ {
		s := &seat{Life: t.life[p]}
		var lib []string
		paid := map[string]int{}
		if p == 0 {
			for n, c := range poolPaidLands[t.jc.Name+"#"+t.m.Name] {
				paid[n] = c
			}
		}
		for _, ac := range t.setup[p] {
			if ac.zone == "battlefield" && paid[ac.name] > 0 {
				n := min(ac.count, paid[ac.name])
				paid[ac.name] -= n
				ac.count -= n
			}
			if dropLands && ac.zone == "battlefield" && basicLands[ac.name] && !t.allNames[ac.name] && !t.needAll {
				continue
			}
			for i := 0; i < ac.count; i++ {
				switch ac.zone {
				case "battlefield":
					s.Battlefield = append(s.Battlefield, ac.name)
					if ac.tapped {
						s.Tapped = append(s.Tapped, ac.name)
					}
				case "hand":
					s.Hand = append(s.Hand, ac.name)
				case "graveyard":
					s.Graveyard = append(s.Graveyard, ac.name)
				case "exile":
					s.Exile = append(s.Exile, ac.name)
				case "library_top":
					lib = append(lib, ac.name)
				}
			}
		}
		// XMage puts each library card on top in turn: the last added is on top.
		for i := len(lib) - 1; i >= 0; i-- {
			s.LibraryTop = append(s.LibraryTop, lib[i])
		}
		if len(s.Tapped) > 0 && len(dedupe(s.Tapped)) != len(s.Tapped) {
			return nil, nil, refuse("tapped-subset", "tapped duplicates")
		}
		s.Tapped = dedupe(s.Tapped)
		for _, n := range s.Tapped {
			cnt := 0
			for _, b := range s.Battlefield {
				if b == n {
					cnt++
				}
			}
			untapped := 0
			for _, ac := range t.setup[p] {
				if ac.zone == "battlefield" && ac.name == n && !ac.tapped {
					untapped++
				}
			}
			if untapped > 0 {
				return nil, nil, refuse("tapped-subset", "%s partly tapped", n)
			}
		}
		if s.Life != nil || len(s.Hand)+len(s.Battlefield)+len(s.Graveyard)+len(s.Exile)+len(s.LibraryTop) > 0 {
			sc.Setup[pref(p)] = s
		}
		// placements in runner bind order
		ords := map[string]int{}
		for _, z := range runnerZoneOrder {
			var names []string
			switch z {
			case "battlefield":
				names = s.Battlefield
			case "hand":
				names = s.Hand
			case "graveyard":
				names = s.Graveyard
			case "exile":
				names = s.Exile
			case "library_top":
				names = s.LibraryTop
			}
			for _, n := range names {
				ords[n]++
				t.places[p] = append(t.places[p], &placement{name: n, zone: z, ord: ords[n]})
			}
		}
		t.castRefs[p] = map[string][]string{}
	}
	if len(sc.Setup) == 0 {
		sc.Setup["p0"] = &seat{}
	}

	// Merge attack/block declarations per turn.
	var acts []*action
	attackOf := map[int]*action{}
	blockOf := map[int]*action{}
	for _, a := range t.actions {
		switch a.kind {
		case "attack":
			if x := attackOf[a.turn]; x != nil {
				if x.seat != a.seat {
					return nil, nil, refuse("bad-args", "two attackers seats")
				}
				if x.defender != a.defender {
					// the runner's attack step names one defender
					return nil, nil, refuse("multi-defender", "turn %d attacks p%d and p%d", a.turn, x.defender, a.defender)
				}
				x.attackers = append(x.attackers, a.attackers...)
				x.choices = append(x.choices, a.choices...)
				continue
			}
			attackOf[a.turn] = a
		case "block":
			if x := blockOf[a.turn]; x != nil {
				x.blocks = append(x.blocks, a.blocks...)
				x.choices = append(x.choices, a.choices...)
				continue
			}
			blockOf[a.turn] = a
		}
		acts = append(acts, a)
	}
	for turn, b := range blockOf {
		if attackOf[turn] == nil {
			return nil, nil, refuse("bad-args", "block without attack on turn %d", turn)
		}
		_ = b
	}
	sort.SliceStable(acts, func(i, j int) bool {
		a, b := acts[i], acts[j]
		if a.turn != b.turn {
			return a.turn < b.turn
		}
		if a.step != b.step {
			return a.step < b.step
		}
		if a.sub != b.sub {
			return a.sub < b.sub
		}
		// A checkpoint assert or a wait is evaluated where the XMage method
		// states it, so it follows source order. The active-seat tiebreak
		// below orders simultaneous casts, but applying it to a check put
		// the active seat's check before the opponent's later cast it
		// actually follows (ThousandYearStorm's checkLife at end of turn
		// rode the second Bolt's cast step and saw 20 life, not 17).
		if a.kind == "check" || a.kind == "wait" || b.kind == "check" || b.kind == "wait" {
			return a.src < b.src
		}
		an, bn := a.seat != t.active(a.turn), b.seat != t.active(b.turn)
		if an != bn {
			return !an
		}
		return a.src < b.src
	})
	for _, pc := range t.pendingChecks {
		xs, r := t.mapAssert(pc.c)
		if r != nil {
			return nil, nil, r
		}
		pc.a.expects = xs
	}

	em := &emitter{t: t, turn: 1, stp: sMain1, attacked: map[int]bool{}, declared: map[int]bool{}, blocked: map[int]bool{}, defender: map[int]int{}}
	for turn, a := range attackOf {
		if len(a.attackers) > 0 {
			em.attacked[turn] = true
		}
		em.defender[turn] = a.defender
	}
	var groups []*group
	for _, a := range acts {
		g, r := em.emit(a)
		if r != nil {
			return nil, nil, r
		}
		a.endAt = len(em.steps)
		if g != nil {
			groups = append(groups, g)
		}
	}
	if r := em.stopAt(t.stop[0], t.stop[1]); r != nil {
		return nil, nil, r
	}
	if len(t.tailChoices) > 0 {
		g, r := t.tailGroup()
		if r != nil {
			return nil, nil, r
		}
		groups = append(groups, g)
	}
	if r := t.manaSideEffects(em.steps); r != nil {
		return nil, nil, r
	}
	if r := t.replicateChoiceRefusal(); r != nil {
		return nil, nil, r
	}
	for _, c := range t.asserts {
		xs, r := t.mapAssert(c)
		if r != nil {
			return nil, nil, r
		}
		sc.Expect = append(sc.Expect, xs...)
	}
	if t.droppedOrder > 0 {
		sc.Why += fmt.Sprintf(" %d XMage trigger-order choice(s) dropped (gorge keeps the offered order).", t.droppedOrder)
	}
	if t.droppedPreAsserts > 0 {
		sc.Why += fmt.Sprintf(" %d assert(s) before execute() dropped (XMage checks them against the game before setup).", t.droppedPreAsserts)
	}
	if len(sc.Expect) == 0 && !em.hasStepExpects {
		return nil, nil, refuse("no-asserts", "no assertion")
	}
	if sc.Expect == nil {
		sc.Expect = []*expect{}
	}
	// sc.Turn is the runner's START turn; the generated steps walk from
	// turn 1, so it stays unset (40 filler cards cover a 12-turn walk).
	sc.Steps = em.steps
	if sc.Steps == nil {
		sc.Steps = []*step{}
	}
	return sc, groups, nil
}

func dedupe(xs []string) []string {
	var out []string
	seen := map[string]bool{}
	for _, x := range xs {
		if !seen[x] {
			seen[x] = true
			out = append(out, x)
		}
	}
	return out
}

func kebab(s string) string {
	var b strings.Builder
	for i, r := range s {
		if r == '_' {
			b.WriteByte('-')
			continue
		}
		if unicode.IsUpper(r) && i > 0 {
			prev := rune(s[i-1])
			if prev != '_' && !unicode.IsUpper(prev) {
				b.WriteByte('-')
			}
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return strings.Trim(strings.ReplaceAll(b.String(), "--", "-"), "-")
}

// ---- refs ----

func refStr(p int, name string, ord int) string {
	if ord <= 1 {
		return fmt.Sprintf("p%d:%s", p, name)
	}
	return fmt.Sprintf("p%d:%s#%d", p, name, ord)
}

// castRef consumes the next castable placement of name for seat p.
func (t *translator) castRef(p int, name string, zones ...string) (string, bool) {
	for _, z := range zones {
		for _, pl := range t.places[p] {
			if pl.zone == z && !pl.used && sameName(pl.name, name) {
				pl.used = true
				r := refStr(p, pl.name, pl.ord)
				t.castRefs[p][name] = append(t.castRefs[p][name], r)
				return r, true
			}
		}
	}
	return "", false
}

func sameName(a, b string) bool {
	if strings.EqualFold(a, b) {
		return true
	}
	// split/adventure: "Fire // Ice" vs "Fire"
	if i := strings.Index(a, " // "); i > 0 {
		return strings.EqualFold(a[:i], b) || strings.EqualFold(a[i+4:], b)
	}
	return false
}

// permRefs lists the refs a permanent named name controlled by p may carry:
// battlefield placements first, then cards cast from other zones.
func (t *translator) permRefs(p int, name string) []string {
	var out []string
	for _, pl := range t.places[p] {
		if pl.zone == "battlefield" && sameName(pl.name, name) {
			out = append(out, refStr(p, pl.name, pl.ord))
		}
	}
	out = append(out, t.castRefs[p][name]...)
	return out
}

// anyRefs lists every ref for name for seat p: permanents then other zones.
func (t *translator) anyRefs(p int, name string) []string {
	out := t.permRefs(p, name)
	seen := map[string]bool{}
	for _, r := range out {
		seen[r] = true
	}
	for _, pl := range t.places[p] {
		r := refStr(p, pl.name, pl.ord)
		if sameName(pl.name, name) && !seen[r] {
			out = append(out, r)
		}
	}
	return out
}

func isTokenName(n string) (string, bool) {
	if strings.HasSuffix(n, " Token") {
		return strings.TrimSuffix(n, " Token"), true
	}
	return n, false
}

// targetRefN maps an XMage target/choice name to a gorge pick, preferring
// the acting seat's objects for nothing: XMage resolves by name over every
// object, so a name present for both seats is refused as ambiguous. It is
// for the ord-th (0-based) pick of one name: an
// addTarget(player, name, 2) or a spell naming the same card twice means two
// different cards of that name, which the runner refs as pN:Name,
// pN:Name#2. A repeated bare ref would bind the first copy twice and be
// rejected as not offered. A name with a single card keeps its one ref.
func (t *translator) targetRefN(name string, ord int) (string, *refusal) {
	if isSeatRef(name) {
		return name, nil
	}
	n, r := xmageName(name)
	if r != nil {
		return "", r
	}
	if _, tok := isTokenName(n); tok {
		return "", refuse("token-target", "%s", n)
	}
	if t.copied[n] {
		return "", refuse("copy-ambiguous-ref", "target %s after a copy of it", n)
	}
	rs, many := t.oneSeatRefs(n)
	switch {
	case many:
		return "", refuse("ambiguous-target", "%s on both seats", n)
	case len(rs) > 0:
		return rs[min(ord, len(rs)-1)], nil
	}
	return "", refuse("target-not-in-setup", "%s", n)
}

// targetRefs maps a step's target names in order, numbering the repeats of
// one name so each names its own card (see targetRefN).
func (t *translator) targetRefs(names []string) ([]string, *refusal) {
	seen := map[string]int{}
	out := make([]string, 0, len(names))
	for _, x := range names {
		r, rr := t.targetRefN(x, seen[x])
		if rr != nil {
			return nil, rr
		}
		seen[x]++
		out = append(out, r)
	}
	return out, nil
}

// choicePick maps a setChoice string: a card name becomes its ref, anything
// else stays a label fragment.
func (t *translator) choicePick(s string) string { return t.choicePickN(s, 0) }

// choicePickN is choicePick for the ord-th (0-based) pick of one counted
// setChoice(player, name, n): the ord-th card of that name, which the runner
// refs as pN:Name, pN:Name#2, ... A repeated bare ref binds the first copy
// only and is rejected as not offered.
//
// Known limitation: the ord indexes anyRefs (battlefield first, then setup
// places), not the one zone the choice reads; a seat holding copies of the
// name in two zones could pick across them. The translator does not track
// which zone a choice reads.
func (t *translator) choicePickN(s string, ord int) string {
	n, r := xmageName(s)
	if r != nil {
		return s
	}
	if t.copied[n] {
		// a copy effect gave the name a second object: a setup ref would
		// name the original, a sacrifice or target ask may mean the copy,
		// and the offered options are labelled by name.
		return s
	}
	if rs, many := t.oneSeatRefs(n); !many && len(rs) > 0 {
		return rs[min(ord, len(rs)-1)]
	}
	if _, ok := t.lookup(n); !ok {
		// XMage words an as-enters P/T choice by its result ("a 3/3
		// artifact creature"); gorge labels it "CARDNAME is 3/3.": the
		// P/T is the part both share.
		if pt := rePTChoice.FindString(s); pt != "" {
			return pt
		}
	}
	return s
}

var rePTChoice = regexp.MustCompile(`\b\d+/\d+\b`)

// ---- mana ----

// manaFromCost converts a Forge mana cost ("3 W", "1 GW GW", "X R", "3 GP")
// into the runner's pool string. X refuses.
func manaFromCost(cost string) (string, *refusal) { return manaFromCostX(cost, -1) }

// manaFromCostX is manaFromCost with X announced as x (x < 0: X refuses).
// Each X symbol adds x generic mana.
func manaFromCostX(cost string, x int) (string, *refusal) { return manaFromCostLands(cost, x, "") }

// manaFromCostLands is manaFromCostX paid from the colours of the casting
// seat's untapped basic lands (lands, one colour letter per land, setup
// order), the way XMage's test player pays: a hybrid symbol takes the first
// of its colours a land can make, and generic mana is paid with whatever
// land is left, so an "if {B} was spent" rider sees the Swamps' B. Mana the
// lands cannot supply stays first-colour / colourless.
func manaFromCostLands(cost string, x int, lands string) (string, *refusal) {
	srcs := make([][]byte, len(lands))
	for i := 0; i < len(lands); i++ {
		srcs[i] = []byte{lands[i]}
	}
	return manaFromCostSources(cost, x, srcs, true)
}

// costSlot is one mana symbol of a cost: a fixed colour, a hybrid option set
// ("WB") or generic mana (both zero).
type costSlot struct {
	fixed  byte
	hybrid string
}

// costSlots parses a Forge mana cost into its symbols, in cost order. X
// announced as x (x < 0: refuse) adds x generic slots.
func costSlots(cost string, x int) ([]costSlot, *refusal) {
	var slots []costSlot
	generic := func(n int) {
		for ; n > 0; n-- {
			slots = append(slots, costSlot{})
		}
	}
	for _, tok := range strings.Fields(cost) {
		switch {
		case tok == "X" && x >= 0:
			generic(x)
		case tok == "X" || tok == "Y":
			return nil, refuse("x-cost", "cost %q", cost)
		case allDigits(tok):
			n := 0
			fmt.Sscanf(tok, "%d", &n)
			generic(n)
		case len(tok) == 1 && strings.Contains("WUBRGC", tok):
			slots = append(slots, costSlot{fixed: tok[0]})
		case tok == "S":
			generic(1)
		case reHybrid.MatchString(tok) && strings.HasSuffix(tok, "P"):
			// XMage's test player pays Phyrexian mana with life; the
			// runner's pool cannot say which.
			return nil, refuse("phyrexian-mana", "cost %q", cost)
		case reHybrid.MatchString(tok):
			slots = append(slots, costSlot{hybrid: strings.ReplaceAll(tok, "/", "")})
		case len(tok) == 2 && tok[0] == '2' && strings.ContainsAny(tok[1:], "WUBRG"):
			slots = append(slots, costSlot{fixed: tok[1]})
		case tok == "no" || tok == "cost" || tok == "0":
		default:
			// non-mana cost token (T, Q, Sac<...>, SubCounter<...>, ...)
		}
	}
	return slots, nil
}

// manaFromCostSources pays cost from srcs, one entry per mana the seat's
// battlefield can make (each entry the set of colours that one mana can be,
// setup order; "Any" sources list WUBRG). fill: a slot no source can pay is
// still emitted first-colour / colourless (the legacy behaviour activations
// use); otherwise it is left out of the pool so gorge pays it the way the game
// would (life, an alternative cost) or fails visibly.
func manaFromCostSources(cost string, x int, srcs [][]byte, fill bool) (string, *refusal) {
	slots, r := costSlots(cost, x)
	if r != nil {
		return "", r
	}
	left := append([][]byte(nil), srcs...)
	// take removes and returns the narrowest remaining source able to make
	// one of colours, so an any-colour source is kept for later slots.
	take := func(colours string) (byte, bool) {
		best, bc := -1, byte(0)
		for i, l := range left {
			for j := 0; j < len(colours); j++ {
				if bytes.IndexByte(l, colours[j]) >= 0 && (best < 0 || len(l) < len(left[best])) {
					best, bc = i, colours[j]
					break
				}
			}
		}
		if best < 0 {
			return 0, false
		}
		left = append(left[:best], left[best+1:]...)
		return bc, true
	}
	out := make([]byte, len(slots))
	for i, sl := range slots {
		if sl.fixed != 0 {
			if _, ok := take(string(sl.fixed)); ok || fill {
				out[i] = sl.fixed
			}
		}
	}
	for i, sl := range slots {
		if sl.hybrid == "" {
			continue
		}
		if c, ok := take(sl.hybrid); ok {
			out[i] = c
		} else if fill {
			out[i] = sl.hybrid[0]
		}
	}
	for i, sl := range slots {
		if sl.fixed != 0 || sl.hybrid != "" {
			continue
		}
		if len(left) > 0 {
			c := left[0][0]
			if len(left[0]) > 1 {
				c = 'C' // any-colour or multi-colour source paying generic
				if len(left[0]) == 2 {
					c = left[0][0]
				}
			}
			out[i], left = c, left[1:]
		} else if fill {
			out[i] = 'C'
		}
	}
	res := make([]byte, 0, len(out))
	for _, c := range out {
		if c != 0 {
			res = append(res, c)
		}
	}
	return string(res), nil
}

// basicLandMana lists one colour letter per untapped-at-setup basic land
// seat p starts with, in setup order.
func (t *translator) basicLandMana(p int) string {
	var b strings.Builder
	for _, pl := range t.places[p] {
		if pl.zone != "battlefield" {
			continue
		}
		switch pl.name {
		case "Plains":
			b.WriteByte('W')
		case "Island":
			b.WriteByte('U')
		case "Swamp":
			b.WriteByte('B')
		case "Mountain":
			b.WriteByte('R')
		case "Forest":
			b.WriteByte('G')
		}
	}
	return b.String()
}

// reHybrid is a hybrid or Phyrexian mana token ("GW", "W/U", "UP", "G/P").
var reHybrid = regexp.MustCompile(`^[WUBRG](/?[WUBRGP])+$`)

func allDigits(s string) bool {
	if s == "" {
		return false
	}
	for _, r := range s {
		if r < '0' || r > '9' {
			return false
		}
	}
	return true
}

