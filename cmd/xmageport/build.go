func active(turn int) int { return (turn - 1) % 2 }

func pref(p int) string { return fmt.Sprintf("p%d", p) }

// runnerZoneOrder is the order rules' build binds setup refs in.
var runnerZoneOrder = []string{"battlefield", "hand", "graveyard", "library", "exile", "command", "library_top"}

func (t *translator) build() (*portScenario, []*group, *refusal) {
	// Asserts need to be read before lands are dropped (assertPermanentCount
	// without a name keeps every land).
	for _, c := range t.asserts {
		if c.Name == "assertPermanentCount" && len(c.Args) == 2 {
			t.needAll = true
		}
	}
	for _, pc := range t.pendingChecks {
		if pc.c.Name == "assertPermanentCount" && len(pc.c.Args) == 2 {
			t.needAll = true
		}
	}
	sc := &portScenario{Name: kebab(t.m.Name), CR: []string{}, Setup: map[string]*seat{},
		Why: fmt.Sprintf("Generated by cmd/xmageport from XMage %s#%s.", t.jc.Name, t.m.Name)}
	for p := 0; p < 2; p++ {
		s := &seat{Life: t.life[p]}
		var lib []string
		paid := map[string]int{}
		if p == 0 {
			for n, c := range poolPaidLands[t.jc.Name+"#"+t.m.Name] {
				paid[n] = c
			}
		}
		for _, ac := range t.setup[p] {
			if ac.zone == "battlefield" && paid[ac.name] > 0 {
				n := min(ac.count, paid[ac.name])
				paid[ac.name] -= n
				ac.count -= n
			}
			if dropLands && ac.zone == "battlefield" && basicLands[ac.name] && !t.allNames[ac.name] && !t.needAll {
				continue
			}
			for i := 0; i < ac.count; i++ {
				switch ac.zone {
				case "battlefield":
					s.Battlefield = append(s.Battlefield, ac.name)
					if ac.tapped {
						s.Tapped = append(s.Tapped, ac.name)
					}
				case "hand":
					s.Hand = append(s.Hand, ac.name)
				case "graveyard":
					s.Graveyard = append(s.Graveyard, ac.name)
				case "exile":
					s.Exile = append(s.Exile, ac.name)
				case "library_top":
					lib = append(lib, ac.name)
				}
			}
		}
		// XMage puts each library card on top in turn: the last added is on top.
		for i := len(lib) - 1; i >= 0; i-- {
			s.LibraryTop = append(s.LibraryTop, lib[i])
		}
		if len(s.Tapped) > 0 && len(dedupe(s.Tapped)) != len(s.Tapped) {
			return nil, nil, refuse("tapped-subset", "tapped duplicates")
		}
		s.Tapped = dedupe(s.Tapped)
		for _, n := range s.Tapped {
			cnt := 0
			for _, b := range s.Battlefield {
				if b == n {
					cnt++
				}
			}
			untapped := 0
			for _, ac := range t.setup[p] {
				if ac.zone == "battlefield" && ac.name == n && !ac.tapped {
					untapped++
				}
			}
			if untapped > 0 {
				return nil, nil, refuse("tapped-subset", "%s partly tapped", n)
			}
		}
		if s.Life != nil || len(s.Hand)+len(s.Battlefield)+len(s.Graveyard)+len(s.Exile)+len(s.LibraryTop) > 0 {
			sc.Setup[pref(p)] = s
		}
		// placements in runner bind order
		ords := map[string]int{}
		for _, z := range runnerZoneOrder {
			var names []string
			switch z {
			case "battlefield":
				names = s.Battlefield
			case "hand":
				names = s.Hand
			case "graveyard":
				names = s.Graveyard
			case "exile":
				names = s.Exile
			case "library_top":
				names = s.LibraryTop
			}
			for _, n := range names {
				ords[n]++
				t.places[p] = append(t.places[p], &placement{name: n, zone: z, ord: ords[n]})
			}
		}
		t.castRefs[p] = map[string][]string{}
	}
	if sc.Setup["p0"] == nil && sc.Setup["p1"] == nil {
		sc.Setup["p0"] = &seat{}
	}

	// Merge attack/block declarations per turn.
	var acts []*action
	attackOf := map[int]*action{}
	blockOf := map[int]*action{}
	for _, a := range t.actions {
		switch a.kind {
		case "attack":
			if x := attackOf[a.turn]; x != nil {
				if x.seat != a.seat {
					return nil, nil, refuse("bad-args", "two attackers seats")
				}
				x.attackers = append(x.attackers, a.attackers...)
				x.choices = append(x.choices, a.choices...)
				continue
			}
			attackOf[a.turn] = a
		case "block":
			if x := blockOf[a.turn]; x != nil {
				x.blocks = append(x.blocks, a.blocks...)
				x.choices = append(x.choices, a.choices...)
				continue
			}
			blockOf[a.turn] = a
		}
		acts = append(acts, a)
	}
	for turn, b := range blockOf {
		if attackOf[turn] == nil {
			return nil, nil, refuse("bad-args", "block without attack on turn %d", turn)
		}
		_ = b
	}
	sort.SliceStable(acts, func(i, j int) bool {
		a, b := acts[i], acts[j]
		if a.turn != b.turn {
			return a.turn < b.turn
		}
		if a.step != b.step {
			return a.step < b.step
		}
		if a.sub != b.sub {
			return a.sub < b.sub
		}
		an, bn := a.seat != active(a.turn), b.seat != active(b.turn)
		if an != bn {
			return !an
		}
		return a.src < b.src
	})
	for _, pc := range t.pendingChecks {
		xs, r := t.mapAssert(pc.c)
		if r != nil {
			return nil, nil, r
		}
		pc.a.expects = xs
	}

	em := &emitter{t: t, turn: 1, stp: sMain1, attacked: map[int]bool{}, declared: map[int]bool{}, blocked: map[int]bool{}}
	for turn, a := range attackOf {
		if len(a.attackers) > 0 {
			em.attacked[turn] = true
		}
	}
	var groups []*group
	for _, a := range acts {
		g, r := em.emit(a)
		if r != nil {
			return nil, nil, r
		}
		if g != nil {
			groups = append(groups, g)
		}
	}
	if r := em.stopAt(t.stop[0], t.stop[1]); r != nil {
		return nil, nil, r
	}
	if len(t.tailChoices) > 0 {
		g, r := t.tailGroup()
		if r != nil {
			return nil, nil, r
		}
		groups = append(groups, g)
	}
	if r := t.manaSideEffects(em.steps); r != nil {
		return nil, nil, r
	}
	for _, c := range t.asserts {
		xs, r := t.mapAssert(c)
		if r != nil {
			return nil, nil, r
		}
		sc.Expect = append(sc.Expect, xs...)
	}
	if t.droppedOrder > 0 {
		sc.Why += fmt.Sprintf(" %d XMage trigger-order choice(s) dropped (gorge keeps the offered order).", t.droppedOrder)
	}
	if len(sc.Expect) == 0 && !em.hasStepExpects {
		return nil, nil, refuse("no-asserts", "no assertion")
	}
	if sc.Expect == nil {
		sc.Expect = []*expect{}
	}
	// sc.Turn is the runner's START turn; the generated steps walk from
	// turn 1, so it stays unset (40 filler cards cover a 12-turn walk).
	sc.Steps = em.steps
	if sc.Steps == nil {
		sc.Steps = []*step{}
	}
	return sc, groups, nil
}

func dedupe(xs []string) []string {
	var out []string
	seen := map[string]bool{}
	for _, x := range xs {
		if !seen[x] {
			seen[x] = true
			out = append(out, x)
		}
	}
	return out
}

func kebab(s string) string {
	var b strings.Builder
	for i, r := range s {
		if r == '_' {
			b.WriteByte('-')
			continue
		}
		if unicode.IsUpper(r) && i > 0 {
			prev := rune(s[i-1])
			if prev != '_' && !unicode.IsUpper(prev) {
				b.WriteByte('-')
			}
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return strings.Trim(strings.ReplaceAll(b.String(), "--", "-"), "-")
}

// ---- refs ----

func refStr(p int, name string, ord int) string {
	if ord <= 1 {
		return fmt.Sprintf("p%d:%s", p, name)
	}
	return fmt.Sprintf("p%d:%s#%d", p, name, ord)
}

// castRef consumes the next castable placement of name for seat p.
func (t *translator) castRef(p int, name string, zones ...string) (string, bool) {
	for _, z := range zones {
		for _, pl := range t.places[p] {
			if pl.zone == z && !pl.used && sameName(pl.name, name) {
				pl.used = true
				r := refStr(p, pl.name, pl.ord)
				t.castRefs[p][name] = append(t.castRefs[p][name], r)
				return r, true
			}
		}
	}
	return "", false
}

func sameName(a, b string) bool {
	if strings.EqualFold(a, b) {
		return true
	}
	// split/adventure: "Fire // Ice" vs "Fire"
	if i := strings.Index(a, " // "); i > 0 {
		return strings.EqualFold(a[:i], b) || strings.EqualFold(a[i+4:], b)
	}
	return false
}

// permRefs lists the refs a permanent named name controlled by p may carry:
// battlefield placements first, then cards cast from other zones.
func (t *translator) permRefs(p int, name string) []string {
	var out []string
	for _, pl := range t.places[p] {
		if pl.zone == "battlefield" && sameName(pl.name, name) {
			out = append(out, refStr(p, pl.name, pl.ord))
		}
	}
	out = append(out, t.castRefs[p][name]...)
	return out
}

// anyRefs lists every ref for name for seat p: permanents then other zones.
func (t *translator) anyRefs(p int, name string) []string {
	out := t.permRefs(p, name)
	seen := map[string]bool{}
	for _, r := range out {
		seen[r] = true
	}
	for _, pl := range t.places[p] {
		r := refStr(p, pl.name, pl.ord)
		if sameName(pl.name, name) && !seen[r] {
			out = append(out, r)
		}
	}
	return out
}

func isTokenName(n string) (string, bool) {
	if strings.HasSuffix(n, " Token") {
		return strings.TrimSuffix(n, " Token"), true
	}
	return n, false
}

// targetRef maps an XMage target/choice name to a gorge pick, preferring
// the acting seat's objects for nothing: XMage resolves by name over every
// object, so a name present for both seats is refused as ambiguous.
func (t *translator) targetRef(name string) (string, *refusal) {
	if name == "p0" || name == "p1" {
		return name, nil
	}
	n, r := xmageName(name)
	if r != nil {
		return "", r
	}
	if _, tok := isTokenName(n); tok {
		return "", refuse("token-target", "%s", n)
	}
	if t.copied[n] {
		return "", refuse("copy-ambiguous-ref", "target %s after a copy of it", n)
	}
	r0, r1 := t.anyRefs(0, n), t.anyRefs(1, n)
	switch {
	case len(r0) > 0 && len(r1) > 0:
		return "", refuse("ambiguous-target", "%s on both seats", n)
	case len(r0) > 0:
		return r0[0], nil
	case len(r1) > 0:
		return r1[0], nil
	}
	return "", refuse("target-not-in-setup", "%s", n)
}

// choicePick maps a setChoice string: a card name becomes its ref, anything
// else stays a label fragment.
func (t *translator) choicePick(s string) string {
	n, r := xmageName(s)
	if r != nil {
		return s
	}
	if t.copied[n] {
		// a copy effect gave the name a second object: a setup ref would
		// name the original, a sacrifice or target ask may mean the copy,
		// and the offered options are labelled by name.
		return s
	}
	r0, r1 := t.anyRefs(0, n), t.anyRefs(1, n)
	if len(r0) > 0 && len(r1) == 0 {
		return r0[0]
	}
	if len(r1) > 0 && len(r0) == 0 {
		return r1[0]
	}
	if _, ok := t.lookup(n); !ok {
		// XMage words an as-enters P/T choice by its result ("a 3/3
		// artifact creature"); gorge labels it "CARDNAME is 3/3.": the
		// P/T is the part both share.
		if pt := rePTChoice.FindString(s); pt != "" {
			return pt
		}
	}
	return s
}

var rePTChoice = regexp.MustCompile(`\b\d+/\d+\b`)

