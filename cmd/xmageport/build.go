// manaFromCost converts a Forge mana cost ("3 W", "1 GW GW", "X R", "3 GP")
// into the runner's pool string. X refuses.
func manaFromCost(cost string) (string, *refusal) { return manaFromCostX(cost, -1) }

// manaFromCostX is manaFromCost with X announced as x (x < 0: X refuses).
// Each X symbol adds x generic mana.
func manaFromCostX(cost string, x int) (string, *refusal) { return manaFromCostLands(cost, x, "") }

// manaFromCostLands is manaFromCostX paid from the colours of the casting
// seat's untapped basic lands (lands, one colour letter per land, setup
// order), the way XMage's test player pays: a hybrid symbol takes the first
// of its colours a land can make, and generic mana is paid with whatever
// land is left, so an "if {B} was spent" rider sees the Swamps' B. Mana the
// lands cannot supply stays first-colour / colourless.
func manaFromCostLands(cost string, x int, lands string) (string, *refusal) {
	// slots keep the cost's symbol order; a slot is a fixed colour, a hybrid
	// option set ("WB") or generic mana ("").
	type slot struct {
		fixed  byte
		hybrid string
	}
	var slots []slot
	generic := func(n int) {
		for ; n > 0; n-- {
			slots = append(slots, slot{})
		}
	}
	for _, tok := range strings.Fields(cost) {
		switch {
		case tok == "X" && x >= 0:
			generic(x)
		case tok == "X" || tok == "Y":
			return "", refuse("x-cost", "cost %q", cost)
		case allDigits(tok):
			n := 0
			fmt.Sscanf(tok, "%d", &n)
			generic(n)
		case len(tok) == 1 && strings.Contains("WUBRGC", tok):
			slots = append(slots, slot{fixed: tok[0]})
		case tok == "S":
			generic(1)
		case reHybrid.MatchString(tok) && strings.HasSuffix(tok, "P"):
			// XMage's test player pays Phyrexian mana with life; the
			// runner's pool cannot say which.
			return "", refuse("phyrexian-mana", "cost %q", cost)
		case reHybrid.MatchString(tok):
			slots = append(slots, slot{hybrid: strings.ReplaceAll(tok, "/", "")})
		case len(tok) == 2 && tok[0] == '2' && strings.ContainsAny(tok[1:], "WUBRG"):
			slots = append(slots, slot{fixed: tok[1]})
		case tok == "no" || tok == "cost" || tok == "0":
		default:
			// non-mana cost token (T, Q, Sac<...>, SubCounter<...>, ...)
		}
	}
	left := []byte(lands)
	take := func(c byte) bool {
		for i, l := range left {
			if l == c {
				left = append(left[:i], left[i+1:]...)
				return true
			}
		}
		return false
	}
	for _, sl := range slots {
		if sl.fixed != 0 {
			take(sl.fixed)
		}
	}
	out := make([]byte, len(slots))
	for i, sl := range slots {
		switch {
		case sl.fixed != 0:
			out[i] = sl.fixed
		case sl.hybrid != "":
			out[i] = sl.hybrid[0]
			for j := 0; j < len(sl.hybrid); j++ {
				if take(sl.hybrid[j]) {
					out[i] = sl.hybrid[j]
					break
				}
			}
		}
	}
	for i, sl := range slots {
		if sl.fixed != 0 || sl.hybrid != "" {
			continue
		}
		out[i] = 'C'
		if len(left) > 0 {
			out[i], left = left[0], left[1:]
		}
	}
	return string(out), nil
}

// basicLandMana lists one colour letter per untapped-at-setup basic land
// seat p starts with, in setup order.
func (t *translator) basicLandMana(p int) string {
	var b strings.Builder
	for _, pl := range t.places[p] {
		if pl.zone != "battlefield" {
			continue
		}
		switch pl.name {
		case "Plains":
			b.WriteByte('W')
		case "Island":
			b.WriteByte('U')
		case "Swamp":
			b.WriteByte('B')
		case "Mountain":
			b.WriteByte('R')
		case "Forest":
			b.WriteByte('G')
		}
	}
	return b.String()
}

// reHybrid is a hybrid or Phyrexian mana token ("GW", "W/U", "UP", "G/P").
var reHybrid = regexp.MustCompile(`^[WUBRG](/?[WUBRGP])+$`)

func allDigits(s string) bool {
	if s == "" {
		return false
	}
	for _, r := range s {
		if r < '0' || r > '9' {
			return false
		}
	}
	return true
}

// ---- abilities ----

type abilityPick struct {
	ref   string
	refs  []string // every same-named source, setup order
	index int
	sa    *cards.SA
	face  *cards.Face
}

func normAbility(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	s = strings.ReplaceAll(s, "  ", " ")
	return s
}

// findAbility resolves activateAbility's rule-text prefix to a source and an
// IR ability index, matching it against oraclegen.XMageAbility's selector
// prefixes for every card seat p has.
func (t *translator) findAbility(p int, text string) (*abilityPick, *refusal) {
	x := normAbility(text)
	type cand struct {
		name  string
		perm  bool
		index int
		sa    *cards.SA
		face  *cards.Face
		exact bool
	}
	var cands []cand
	seen := map[string]bool{}
	names := []string{}
	for _, pl := range t.places[p] {
		if !seen[pl.name] {
			seen[pl.name] = true
			names = append(names, pl.name)
		}
	}
	for _, n := range names {
		c, ok := t.lookup(n)
		if !ok {
			continue
		}
		for _, f := range c.Faces {
			if f == nil {
				continue
			}
			m, _ := oraclegen.XMageAbility(f)
			idxs := make([]int, 0, len(m))
			for i := range m {
				idxs = append(idxs, i)
			}
			sort.Ints(idxs)
			for _, i := range idxs {
				pfx := normAbility(m[i])
				if pfx == "" {
					continue
				}
				if strings.HasPrefix(x, pfx) || strings.HasPrefix(pfx, x) {
					cands = append(cands, cand{name: n, perm: len(t.permRefs(p, n)) > 0, index: i, sa: f.Abilities[i], face: f, exact: strings.HasPrefix(x, pfx)})
				}
			}
		}
	}
	if len(cands) == 0 {
		return nil, refuse("ability-unresolved", "%q", text)
	}
	// prefer exact selector matches, then permanents, then the lowest index
	best := cands[:0:0]
	for _, c := range cands {
		if c.exact {
			best = append(best, c)
		}
	}
	if len(best) == 0 {
		best = cands
	}
	var perm []cand
	for _, c := range best {
		if c.perm {
			perm = append(perm, c)
		}
	}
	if len(perm) > 0 {
		best = perm
	}
	srcs := map[string]bool{}
	for _, c := range best {
		srcs[c.name] = true
	}
	if len(srcs) > 1 {
		return nil, refuse("ability-ambiguous", "%q matches %d cards", text, len(srcs))
	}
	c := best[0]
	refs := t.permRefs(p, c.name)
	if len(refs) == 0 {
		refs = t.anyRefs(p, c.name)
	}
	if len(refs) == 0 {
		return nil, refuse("ability-unresolved", "%q source", text)
	}
	return &abilityPick{ref: refs[0], refs: refs, index: c.index, sa: c.sa, face: c.face}, nil
}

// ---- asserts ----

func ip(n int) *int { return &n }

// enumSpelling is the printed spelling of the XMage constants whose name
// drops punctuation.
var enumSpelling = map[string]string{"URZAS": "Urza's"}

func titleEnum(s string) string {
	if i := strings.LastIndex(s, "."); i >= 0 {
		s = s[i+1:]
	}
	if v, ok := enumSpelling[s]; ok {
		return v
	}
	parts := strings.Split(strings.ToLower(s), "_")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, " ")
}

// canCopy reports whether seat p has a setup card that can become a copy of
// another permanent (a face SVar resolving `DB$ Clone`: Clone, Altered Ego,
// Phantasmal Image).
func (t *translator) canCopy(p int) bool {
	for _, pl := range t.places[p] {
		c, ok := t.lookup(pl.name)
		if !ok {
			continue
		}
		for _, f := range c.Faces {
			for _, body := range f.SVars {
				if strings.Contains(body, "DB$ Clone") {
					return true
				}
			}
		}
	}
	return false
}

// copyOnlyRef returns the ref of seat p's copy of the card named n when p's
// only setup cards of that name are off the battlefield (a graveyard or hand
// card its copy effect copied): an assert on the name is about the copy,
// not the setup card. "" when there is no single such copy.
func (t *translator) copyOnlyRef(p int, n string) string {
	if !t.copied[n] || len(t.permRefs(p, n)) > 0 {
		return ""
	}
	if r := t.copyRef[fmt.Sprintf("%d|%s", p, n)]; r != "-" {
		return r
	}
	return ""
}

// assertRef maps an asserted card name to a ref: tokens by controller, cards
// by the asserting player's objects first, then the other seat's.
func (t *translator) assertRef(p int, name string) (string, *refusal) {
	n, r := xmageName(name)
	if r != nil {
		return "", r
	}
	if base, tok := isTokenName(n); tok {
		if p < 0 {
			return "", refuse("unmappable-assert", "token %s without player", n)
		}
		return fmt.Sprintf("p%d:token:%s", p, base), nil
	}
	if p >= 0 {
		if rs := t.anyRefs(p, n); len(rs) > 0 {
			if r := t.copyOnlyRef(p, n); r != "" {
				return r, nil
			}
			return rs[0], nil
		}
		if t.copied[n] {
			// p's copy of the other seat's card: the copy's own ref
			if r := t.copyRef[fmt.Sprintf("%d|%s", p, n)]; r != "" && r != "-" {
				return r, nil
			}
			return "", refuse("copy-ambiguous-ref", "assert on p%d's copy of %s", p, n)
		}
		if rs := t.anyRefs(1-p, n); len(rs) > 0 {
			// A copy of the other seat's card is named for the original
			// but owned by p: bind the assert to p's object, not the original.
			if t.canCopy(p) {
				return fmt.Sprintf("p%d:%s", p, n), nil
			}
			return rs[0], nil
		}
		return "", refuse("assert-not-in-setup", "%s", n)
	}
	r0, r1 := t.anyRefs(0, n), t.anyRefs(1, n)
	if len(r0) > 0 != (len(r1) > 0) {
		for _, p := range []int{0, 1} {
			if r := t.copyOnlyRef(p, n); r != "" {
				return r, nil
			}
		}
	}
	switch {
	case len(r0) > 0 && len(r1) > 0:
		return "", refuse("unmappable-assert", "%s on both seats", n)
	case len(r0) > 0:
		return r0[0], nil
	case len(r1) > 0:
		return r1[0], nil
	}
	return "", refuse("assert-not-in-setup", "%s", n)
}

// runnerLibrary is the filler library the scenario runner deals each seat
// (engine/rules/oracle_run.go).
const runnerLibrary = 40

func countExpect(p int, zone, name string, n int) (*expect, *refusal) {
	nm, r := xmageName(name)
	if r != nil {
		return nil, r
	}
	if nm == "" && n >= runnerLibrary && zone != "battlefield" && zone != "hand" {
		// a seat-wide count this large counts XMage's test library, which
		// is not the runner's 40 filler cards
		return nil, refuse("library-size", "%s count %d", zone, n)
	}
	c := &count{Seat: p, Zone: zone, Name: nm}
	if base, tok := isTokenName(nm); tok {
		c.Name = base
		tr := true
		c.Token = &tr
	}
	return &expect{Count: c, Eq: ip(n)}, nil
}

func (t *translator) mapAssert(c call) ([]*expect, *refusal) {
	a := c.Args
	bad := func() ([]*expect, *refusal) { return nil, refuse("unmappable-assert", "%s(%d args)", c.Name, len(a)) }
	switch c.Name {
	case "assertLife":
		p, ok := seatOf(a[0])
		n, ok2 := argInt(c, 1)
		if !ok || !ok2 {
			return bad()
		}
		return []*expect{{Life: map[string]int32{pref(p): int32(n)}}}, nil
	case "assertPermanentCount", "assertGraveyardCount", "assertHandCount", "assertExileCount":
		zone := map[string]string{"assertPermanentCount": "battlefield", "assertGraveyardCount": "graveyard",
			"assertHandCount": "hand", "assertExileCount": "exile"}[c.Name]
		switch len(a) {
		case 2:
			if p, ok := seatOf(a[0]); ok {
				n, ok := argInt(c, 1)
				if !ok {
					return bad()
				}
				switch zone {
				case "hand":
					return []*expect{{HandSize: map[string]int{pref(p): n}}}, nil
				case "graveyard":
					return []*expect{{GraveyardSize: map[string]int{pref(p): n}}}, nil
				}
				e, r := countExpect(p, zone, "", n)
				return []*expect{e}, r
			}
			// assertExileCount(name, n): owner from setup
			name, ok := argStr(c, 0)
			n, ok2 := argInt(c, 1)
			if !ok || !ok2 {
				return bad()
			}
			ref, r := t.assertRef(-1, name)
			if r != nil {
				return nil, r
			}
			e, r := countExpect(int(ref[1]-'0'), zone, name, n)
			return []*expect{e}, r
		case 3:
			p, ok := seatOf(a[0])
			name, ok2 := argStr(c, 1)
			n, ok3 := argInt(c, 2)
			if !ok || !ok2 || !ok3 {
				return bad()
			}
			e, r := countExpect(p, zone, name, n)
			return []*expect{e}, r
		}
		return bad()
	case "assertPowerToughness":
		if len(a) < 4 {
			return bad()
		}
		p, ok := seatOf(a[0])
		name, ok2 := argStr(c, 1)
		pw, ok3 := argInt(c, 2)
		tg, ok4 := argInt(c, 3)
		if !ok || !ok2 || !ok3 || !ok4 {
			return bad()
		}
		if len(a) > 4 && a[4].s != "Filter.ComparisonScope.Any" && a[4].s != "Filter.ComparisonScope.All" {
			return bad()
		}
		ref, r := t.assertRef(p, name)
		if r != nil {
			return nil, r
		}
		return []*expect{{Card: ref, PT: fmt.Sprintf("%d/%d", pw, tg)}}, nil
	case "assertCounterCount":
		var p = -1
		if q, ok := seatOf(a[0]); ok {
			p = q
			a = a[1:]
		}
		if len(a) != 3 || a[0].kind != vStr || a[2].kind != vInt {
			return bad()
		}
		kind := ""
		switch a[1].kind {
		case vIdent:
			kind = strings.TrimPrefix(a[1].s, "CounterType.")
		case vStr:
			kind = a[1].s
		default:
			return bad()
		}
		ref, r := t.assertRef(p, a[0].s)
		if r != nil {
			return nil, r
		}
		return []*expect{{Card: ref, Counters: map[string]int32{kind: int32(a[2].n)}}}, nil
	case "assertType", "assertSubtype", "assertNotSubtype":
		if len(a) < 2 || a[0].kind != vStr {
			return bad()
		}
		ref, r := t.assertRef(-1, a[0].s)
		if r != nil {
			return nil, r
		}
		e := &expect{Card: ref}
		switch c.Name {
		case "assertSubtype":
			e.Types = []string{titleEnum(a[1].s)}
		case "assertNotSubtype":
			e.NoTypes = []string{titleEnum(a[1].s)}
		default:
			if len(a) != 3 {
				return bad()
			}
			ty := titleEnum(a[1].s)
			switch a[2].kind {
			case vBool:
				if a[2].b {
					e.Types = []string{ty}
				} else {
					e.NoTypes = []string{ty}
				}
			case vIdent:
				e.Types = []string{ty, titleEnum(a[2].s)}
			default:
				return bad()
			}
		}
		return []*expect{e}, nil
	case "assertAbility":
		if len(a) != 4 {
			return bad()
		}
		p, ok := seatOf(a[0])
		name, ok2 := argStr(c, 1)
		if !ok || !ok2 || a[3].kind != vBool {
			return bad()
		}
		cls := a[2].s
		cls = strings.TrimSuffix(cls, ".class")
		kw := keywordAbilities[cls]
		if kw == "" {
			return nil, refuse("ability-assert", "%s", a[2].s)
		}
		ref, r := t.assertRef(p, name)
		if r != nil {
			return nil, r
		}
		e := &expect{Card: ref}
		if a[3].b {
			e.Keywords = []string{kw}
		} else {
			e.NoKeywords = []string{kw}
		}
		return []*expect{e}, nil
	case "assertTapped":
		if len(a) != 2 || a[0].kind != vStr || a[1].kind != vBool {
			return bad()
		}
		ref, r := t.assertRef(-1, a[0].s)
		if r != nil {
			return nil, r
		}
		b := a[1].b
		return []*expect{{Card: ref, Tapped: &b}}, nil
	case "assertTappedCount":
		if len(a) != 3 || a[0].kind != vStr || a[1].kind != vBool || a[2].kind != vInt {
			return bad()
		}
		return t.tappedCount(a[0].s, a[1].b, a[2].n)
	case "assertDamageReceived":
		if len(a) != 3 {
			return bad()
		}
		p, ok := seatOf(a[0])
		name, ok2 := argStr(c, 1)
		n, ok3 := argInt(c, 2)
		if !ok || !ok2 || !ok3 {
			return bad()
		}
		ref, r := t.assertRef(p, name)
		if r != nil {
			return nil, r
		}
		d := int32(n)
		return []*expect{{Card: ref, Damage: &d}}, nil
	case "checkStackSize":
		n, ok := argInt(c, len(a)-1)
		if !ok {
			return bad()
		}
		return []*expect{{StackSize: ip(n)}}, nil
	}
	return nil, refuse("unsupported-assert", "%s", c.Name)
}

// ---- emitter ----

type emitter struct {
	t              *translator
	steps          []*step
	turn, stp      int
	holder         int
	maxTurn        int
	attacked       map[int]bool
	declared       map[int]bool
	blocked        map[int]bool
	hasStepExpects bool
	tappedAt       map[string]int // {T}-cost source ref -> turn last tapped
}

func (em *emitter) add(s *step) *step {
	em.steps = append(em.steps, s)
	return s
}

func (em *emitter) resolve() {
	em.add(&step{Op: "resolve"})
	em.holder = active(em.turn)
}

func (em *emitter) note(turn int) {
	if turn > em.maxTurn {
		em.maxTurn = turn
	}
}

// gotoClock emits the steps that bring the game to priority in step s of
// turn tn.
func (em *emitter) gotoClock(tn, s int) *refusal {
	em.note(tn)
	if tn < em.turn || (tn == em.turn && s < em.stp) {
		return refuse("clock-backwards", "to %d/%s from %d/%s", tn, stepNames[s], em.turn, stepNames[em.stp])
	}
	if tn == em.turn && s == em.stp {
		return nil
	}
	if s == sCleanup || s == sUntap {
		return refuse("no-priority-step", "%s", stepNames[s])
	}
	for em.turn < tn {
		em.turn++
		em.stp = sUpkeep
		em.add(&step{Op: "pass_to", Step: "upkeep", Active: pref(active(em.turn))})
		em.holder = active(em.turn)
	}
	if s == em.stp {
		return nil
	}
	act := active(tn)
	switch s {
	case sDeclareAttackers:
		em.add(&step{Op: "attack", Seat: act, Attackers: []string{}, Defender: pref(1 - act)})
		em.declared[tn] = true
	case sDeclareBlockers:
		if !em.attacked[tn] {
			return refuse("combat-step-without-attackers", "%s on turn %d", stepNames[s], tn)
		}
		if em.t.mayBlock(1 - act) {
			em.add(&step{Op: "block", Seat: 1 - act})
		} else {
			// no creature to block with: gorge poses no blockers ask
			em.add(&step{Op: "pass_to", Step: stepNames[s], Active: pref(act)})
		}
		em.blocked[tn] = true
	case sCombatDamage, sEndCombat:
		if !em.attacked[tn] {
			return refuse("combat-step-without-attackers", "%s on turn %d", stepNames[s], tn)
		}
		em.add(&step{Op: "pass_to", Step: stepNames[s], Active: pref(act)})
	default:
		if s < sMain1 && tn == 1 {
			return refuse("clock-backwards", "turn 1 %s", stepNames[s])
		}
		em.add(&step{Op: "pass_to", Step: stepNames[s], Active: pref(act)})
	}
	em.stp = s
	em.holder = act
	return nil
}

func (em *emitter) sorcerySpeedCast(name string) bool {
	c, ok := em.t.lookup(name)
	if !ok {
		return true
	}
	for _, f := range c.Faces {
		if f == nil || !sameName(f.Name, name) && len(c.Faces) > 1 {
			continue
		}
		for _, ty := range f.Types {
			if ty == "Instant" {
				return false
			}
		}
		for _, k := range f.Keywords {
			if strings.EqualFold(k, "Flash") {
				return false
			}
		}
		return true
	}
	return true
}

func (em *emitter) castMana(seat int, name string, x int) (string, *refusal) {
	c, ok := em.t.lookup(name)
	if !ok {
		return "", refuse("unknown-card", "%s", name)
	}
	for _, f := range c.Faces {
		if f != nil && sameName(f.Name, name) {
			return manaFromCostLands(f.ManaCost, x, em.t.basicLandMana(seat))
		}
	}
	if len(c.Faces) > 0 && c.Faces[0] != nil {
		return manaFromCostLands(c.Faces[0].ManaCost, x, em.t.basicLandMana(seat))
	}
	return "", nil
}

// kickerCost returns the card's Kicker cost ("R", "1 U"), or "".
func (em *emitter) kickerCost(name string) string {
	c, ok := em.t.lookup(name)
	if !ok {
		return ""
	}
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		for _, k := range f.Keywords {
			if strings.HasPrefix(k, "Kicker:") {
				parts := strings.Split(k, ":")
				return parts[1]
			}
		}
	}
	return ""
}

func (em *emitter) priorityTo(seat int) {
	if em.holder != seat {
		em.add(&step{Op: "pass", Seat: em.holder})
		em.holder = seat
	}
}

func (em *emitter) emit(a *action) (*group, *refusal) {
	t := em.t
	var g *group
	attach := func(s *step, hasTargets bool) *refusal {
		if len(a.choices) == 0 {
			return nil
		}
		g = &group{at: len(em.steps) - 1}
		for _, ch := range a.choices {
			seat := ch.seat
			if ch.x >= 0 && a.kind != "cast" && a.kind != "activate" {
				// "X=N" not tied to a spell or ability: a damage-assignment
				// or other amount ask gorge does not pose as a choose.
				return refuse("amount-choice", "setChoice X=%d on %s", ch.x, a.kind)
			}
			pick := ch.pick
			if ch.mode > 0 {
				lbl, r := em.modeLabel(a, ch.mode)
				if r != nil {
					return r
				}
				g.xvals = append(g.xvals, xans{Seat: ch.seat, Kind: "mode", Value: pick})
				g.answers = append(g.answers, answer{Kind: "modes", Pick: []string{lbl}, Seat: &seat})
				continue
			}
			if strings.HasPrefix(pick, "name:") {
				n := strings.TrimPrefix(pick, "name:")
				if ch.target {
					r, rr := t.targetRef(n)
					if rr != nil {
						return rr
					}
					pick = r
				} else {
					pick = t.choicePick(n)
				}
			}
			xk := "choice"
			if ch.target {
				xk = "target"
			}
			g.xvals = append(g.xvals, xans{Seat: ch.seat, Kind: xk, Value: pick})
			if ch.target && !hasTargets {
				g.targets = append(g.targets, pick)
			} else if ch.target {
				g.answers = append(g.answers, answer{Kind: "target", Pick: []string{pick}, Seat: &seat})
			} else if ch.x >= 0 {
				g.answers = append(g.answers, answer{Kind: "choose", Pick: []string{pick}, Seat: &seat})
			} else {
				g.answers = append(g.answers, answer{Kind: "any", Pick: []string{pick}, Seat: &seat})
			}
		}
		return nil
	}
	em.note(a.turn)
	switch a.kind {
	case "cast", "play":
		if r := em.gotoClock(a.turn, a.step); r != nil {
			return nil, r
		}
		sorc := a.kind == "play" || em.t != nil && em.sorcerySpeedCast(a.card)
		if sorc {
			if a.seat != active(a.turn) {
				return nil, refuse("sorcery-speed-off-turn", "%s", a.card)
			}
			if a.step != sMain1 && a.step != sMain2 {
				return nil, refuse("sorcery-speed-off-main", "%s at %s", a.card, stepNames[a.step])
			}
			em.resolve()
		}
		em.priorityTo(a.seat)
		var ref string
		var ok bool
		if a.kind == "play" {
			ref, ok = t.castRef(a.seat, a.card, "hand")
		} else {
			ref, ok = t.castRef(a.seat, a.card, "hand", "graveyard", "exile", "library_top", "battlefield")
		}
		if !ok {
			return nil, refuse("cast-not-in-setup", "%s", a.card)
		}
		s := &step{Op: a.kind, Seat: a.seat, Card: ref}
		if a.kind == "cast" {
			m, r := em.castMana(a.seat, a.card, takeX(a))
			if r != nil {
				return nil, r
			}
			s.Mana = m
			// XMage answers Kicker's "pay the kicker?" with the first
			// setChoice after the cast; gorge offers it as a cast mode.
			if kc := em.kickerCost(a.card); kc != "" && len(a.choices) > 0 && !a.choices[0].target &&
				(a.choices[0].pick == "yes" || a.choices[0].pick == "no") {
				if a.choices[0].pick == "yes" {
					km, r := manaFromCostX(kc, takeX(a))
					if r != nil {
						return nil, r
					}
					s.Mana += km
					s.Kicked = true
				}
				a.choices = a.choices[1:]
			}
			for _, x := range a.targets {
				tr, r := t.targetRef(x)
				if r != nil {
					return nil, r
				}
				s.Targets = append(s.Targets, tr)
			}
		}
		em.add(s)
		if r := attach(s, len(s.Targets) > 0); r != nil {
			return nil, r
		}
		if (a.kind == "cast" || a.kind == "play") && t.isCopyCard(a.card) {
			if !t.isPermanentCard(a.card) {
				t.markCopied(a, "") // a spell's copies are tokens
			} else {
				t.markCopied(a, ref) // the clone itself is the copy
			}
		}
		if a.kind == "cast" && a.resolveAfter {
			em.resolve()
		}
	case "activate":
		if r := em.gotoClock(a.turn, a.step); r != nil {
			return nil, r
		}
		pick, r := t.findAbility(a.seat, a.ability)
		if r != nil {
			return nil, r
		}
		if t.copied[refName(pick.ref)] {
			return nil, refuse("copy-ambiguous-ref", "activate %s after a copy of it", refName(pick.ref))
		}
		pick.ref = em.untappedSource(pick, a.turn)
		if pick.sa.API == "Mana" {
			return nil, refuse("mana-payment", "mana ability %q", a.ability)
		}
		cost := pick.sa.ParamStr(cards.PKCost)
		sorc := pick.sa.HasParam(cards.PKSorcerySpeed) || pick.sa.HasParam(cards.PKPlaneswalker) || strings.Contains(cost, "LOYALTY")
		if sorc {
			if a.seat != active(a.turn) {
				return nil, refuse("sorcery-speed-off-turn", "%q", a.ability)
			}
			em.resolve()
		}
		em.priorityTo(a.seat)
		mana, r := manaFromCostX(cost, takeX(a))
		if r != nil {
			return nil, r
		}
		idx := pick.index
		s := &step{Op: "activate", Seat: a.seat, Card: pick.ref, Mana: mana, AbilityIndex: &idx, XAbility: a.ability}
		for _, x := range a.targets {
			tr, r := t.targetRef(x)
			if r != nil {
				return nil, r
			}
			s.Targets = append(s.Targets, tr)
		}
		em.add(s)
		if r := attach(s, len(s.Targets) > 0); r != nil {
			return nil, r
		}
		if saCopies(pick.sa) {
			t.markCopied(a, "")
		}
	case "wait":
		if r := em.gotoClock(a.turn, a.step); r != nil {
			return nil, r
		}
		em.resolve()
	case "attack":
		if a.turn > em.turn {
			if r := em.gotoClock(a.turn, sUpkeep); r != nil {
				return nil, r
			}
		}
		if a.turn < em.turn || (a.turn == em.turn && em.stp >= sDeclareAttackers) {
			return nil, refuse("clock-backwards", "attack on turn %d", a.turn)
		}
		if a.seat != active(a.turn) {
			return nil, refuse("bad-args", "attack by non-active player")
		}
		used := map[string]int{}
		var refs []string
		for _, n := range a.attackers {
			if t.copied[n] {
				return nil, refuse("copy-ambiguous-ref", "attack with %s after a copy of it", n)
			}
			rs := t.permRefs(a.seat, n)
			k := used[n]
			used[n]++
			if k >= len(rs) {
				return nil, refuse("attacker-not-in-setup", "%s", n)
			}
			refs = append(refs, rs[k])
		}
		s := em.add(&step{Op: "attack", Seat: a.seat, Attackers: refs, Defender: pref(1 - a.seat)})
		em.declared[a.turn] = true
		em.stp = sDeclareAttackers
		em.holder = a.seat
		if r := attach(s, false); r != nil {
			return nil, r
		}
	case "block":
		if !em.declared[a.turn] || em.turn != a.turn || em.stp > sDeclareAttackers {
			return nil, refuse("clock-backwards", "block on turn %d", a.turn)
		}
		atk := t.attackRefs(a.turn)
		used := map[string]int{}
		var blocks [][2]string
		for _, b := range a.blocks {
			rs := t.permRefs(a.seat, b[0])
			k := used[b[0]]
			used[b[0]]++
			if k >= len(rs) {
				return nil, refuse("blocker-not-in-setup", "%s", b[0])
			}
			ar := ""
			for _, x := range atk {
				if refName(x) == b[1] || sameName(refName(x), b[1]) {
					ar = x
					break
				}
			}
			if ar == "" {
				return nil, refuse("bad-args", "block names non-attacker %s", b[1])
			}
			blocks = append(blocks, [2]string{rs[k], ar})
		}
		s := em.add(&step{Op: "block", Seat: a.seat, Blocks: blocks})
		em.blocked[a.turn] = true
		em.stp = sDeclareBlockers
		em.holder = active(a.turn)
		if r := attach(s, false); r != nil {
			return nil, r
		}
	case "check":
		if r := em.gotoClock(a.turn, a.step); r != nil {
			return nil, r
		}
		if len(em.steps) == 0 {
			em.add(&step{Op: "pass_to", Decision: "priority"})
		}
		last := em.steps[len(em.steps)-1]
		last.Expect = append(last.Expect, a.expects...)
		em.hasStepExpects = true
	}
	return g, nil
}

// mayBlock reports whether seat p has a creature that could be asked to
// block (setup battlefield or a cast creature card).
func (t *translator) mayBlock(p int) bool {
	isCreature := func(n string) bool {
		c, ok := t.lookup(n)
		if !ok {
			return true
		}
		for _, f := range c.Faces {
			if f == nil {
				continue
			}
			for _, ty := range f.Types {
				if ty == "Creature" {
					return true
				}
			}
		}
		return false
	}
	for _, pl := range t.places[p] {
		if pl.zone == "battlefield" && isCreature(pl.name) {
			return true
		}
	}
	for n := range t.castRefs[p] {
		if isCreature(n) {
			return true
		}
	}
	return false
}

func refName(ref string) string {
	i := strings.IndexByte(ref, ':')
	n := ref[i+1:]
	if j := strings.LastIndexByte(n, '#'); j >= 0 {
		n = n[:j]
	}
	return n
}

// attackRefs returns the refs declared as attackers on turn tn.
func (t *translator) attackRefs(tn int) []string {
	// the emitter wrote them on the attack step; find it via actions
	for _, a := range t.actions {
		if a.kind == "attack" && a.turn == tn {
			used := map[string]int{}
			var out []string
			for _, n := range a.attackers {
				rs := t.permRefs(a.seat, n)
				k := used[n]
				used[n]++
				if k < len(rs) {
					out = append(out, rs[k])
				}
			}
			return out
		}
	}
	return nil
}

// stopAt emits the steps for setStopAt(tn, s). XMage pauses AFTER it has
// played step s (mage/game/turn/Phase.java: playStep, then
// checkStopOnStepOption), so the asserted state is the END of step s: its
// actions done and its stack resolved.
func (em *emitter) stopAt(tn, s int) *refusal {
	em.note(tn)
	type tgt struct {
		turn, step int
		resolve    bool
	}
	g := tgt{tn, s, true}
	switch s {
	case sUntap:
		g = tgt{tn, sUpkeep, false}
	case sDeclareAttackers:
		if !em.declared[tn] {
			g = tgt{tn, sBeginCombat, true}
		}
	case sDeclareBlockers:
		if !em.attacked[tn] {
			g = tgt{tn, sBeginCombat, true}
		}
	case sCombatDamage:
		// gorge has one step value for both damage steps: stop past both
		if em.attacked[tn] {
			g = tgt{tn, sEndCombat, false}
		} else {
			g = tgt{tn, sBeginCombat, true}
		}
	case sEndCombat:
		if !em.attacked[tn] {
			g = tgt{tn, sBeginCombat, true}
		}
	case sCleanup:
		// the end of cleanup is the next turn's beginning
		g = tgt{tn + 1, sUpkeep, false}
	}
	if g.turn == 1 && g.step < sMain1 {
		g.step = sMain1
	}
	if em.turn == g.turn && g.step < em.stp {
		g.step = em.stp
	}
	if g.turn < em.turn {
		return refuse("clock-backwards", "stop at %d/%s", tn, stepNames[s])
	}
	if r := em.gotoClock(g.turn, g.step); r != nil {
		return r
	}
	if g.resolve {
		em.resolve()
	}
	return nil
}

// takeX returns the action's announced X (the first setChoice "X=N" it
// consumes), or -1. The choice stays queued: gorge poses X as a choose ask.
func takeX(a *action) int {
	for _, ch := range a.choices {
		if ch.x >= 0 {
			return ch.x
		}
	}
	return -1
}

// tappedCount maps assertTappedCount(name, tapped, n): exactly n permanents
// named name have isTapped()==tapped. Expressible per object only when n is
// 0 (all have the other state) or every known instance. Lands refuse: the
// runner pays from the pool, so a land XMage tapped for mana stays untapped.
func (t *translator) tappedCount(name string, tapped bool, n int) ([]*expect, *refusal) {
	nm, r := xmageName(name)
	if r != nil {
		return nil, r
	}
	if c, ok := t.lookup(nm); ok && len(c.Faces) > 0 && c.Faces[0] != nil {
		for _, ty := range c.Faces[0].Types {
			if ty == "Land" {
				return nil, refuse("tapped-land-count", "%s", nm)
			}
		}
	}
	refs := append(t.permRefs(0, nm), t.permRefs(1, nm)...)
	if len(refs) == 0 {
		return nil, refuse("assert-not-in-setup", "%s", nm)
	}
	want := tapped
	switch n {
	case 0:
		want = !tapped
	case len(refs):
	default:
		return nil, refuse("tapped-subset", "assertTappedCount %s %d of %d", nm, n, len(refs))
	}
	var out []*expect
	for _, ref := range refs {
		b := want
		out = append(out, &expect{Card: ref, Tapped: &b})
	}
	return out, nil
}

// modeLabel names the n-th (1-based) Charm mode of the spell a casts as the
// label gorge's modes ask offers (effects.CharmModeLabel over Choices$
// order). Only a cast whose spell ability (or its first sub) is a Charm
// maps; anything else refuses.
func (em *emitter) modeLabel(a *action, n int) (string, *refusal) {
	if a.kind != "cast" {
		return "", refuse("mode-choice", "setModeChoice on %s", a.kind)
	}
	c, ok := em.t.lookup(a.card)
	if !ok {
		return "", refuse("unknown-card", "%s", a.card)
	}
	for _, f := range c.Faces {
		if f == nil || !sameName(f.Name, a.card) && len(c.Faces) > 1 {
			continue
		}
		for sa := f.SpellAbility(); sa != nil; sa = sa.Sub {
			if sa.API != "Charm" {
				continue
			}
			modes := effects.CharmOf(sa).Modes
			if n > len(modes) {
				return "", refuse("mode-choice", "mode %d of %d", n, len(modes))
			}
			return effects.CharmModeLabel(cards.ResolveSVar(f.SVars, modes[n-1]), modes[n-1]), nil
		}
	}
	return "", refuse("mode-choice", "no Charm on %s", a.card)
}

// untappedSource picks which same-named source an activation uses. XMage
// activates the first one that can pay, so a {T} ability already used by
// an untapped-since copy moves on to the next copy (two Rushwood
// Herbalists regenerating twice in one turn).
func (em *emitter) untappedSource(pick *abilityPick, turn int) string {
	if !hasTapCost(pick.sa.ParamStr(cards.PKCost)) {
		return pick.ref
	}
	if em.tappedAt == nil {
		em.tappedAt = map[string]int{}
	}
	seat := int(pick.ref[1] - '0')
	free := func(ref string) bool {
		k, ok := em.tappedAt[ref]
		if !ok {
			return true
		}
		for u := k + 1; u <= turn; u++ {
			if active(u) == seat {
				return true
			}
		}
		return false
	}
	ref := pick.ref
	for _, r := range pick.refs {
		if free(r) {
			ref = r
			break
		}
	}
	em.tappedAt[ref] = turn
	return ref
}

func hasTapCost(cost string) bool {
	for _, tok := range strings.Fields(cost) {
		if tok == "T" {
			return true
		}
	}
	return false
}

// isCopyCard reports whether casting name makes a copy of a permanent: a
// Clone or CopyPermanent ability, direct or through an SVar (an ETB
// "enter as a copy" replacement).
func (t *translator) isCopyCard(name string) bool {
	c, ok := t.lookup(name)
	if !ok {
		return false
	}
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		for _, sa := range f.Abilities {
			if sa != nil && (sa.API == "Clone" || sa.API == "CopyPermanent") {
				return true
			}
		}
		for _, v := range f.SVars {
			if strings.Contains(v, "$ Clone") || strings.Contains(v, "$ CopyPermanent") {
				return true
			}
		}
	}
	return false
}

// isPermanentCard reports whether name's front face is a permanent card.
func (t *translator) isPermanentCard(name string) bool {
	c, ok := t.lookup(name)
	if !ok || len(c.Faces) == 0 || c.Faces[0] == nil {
		return true
	}
	for _, ty := range c.Faces[0].Types {
		if ty == "Instant" || ty == "Sorcery" {
			return false
		}
	}
	return true
}

// saCopies reports whether activating sa makes a permanent copy.
func saCopies(sa *cards.SA) bool {
	for x := sa; x != nil; x = x.Sub {
		if x.API == "Clone" || x.API == "CopyPermanent" {
			return true
		}
	}
	return false
}

// markCopied records the names a copy action's choices and targets name:
// from here on that name may belong to two permanents. The copy itself is
// the cast card (ref) or, for an ability, a token of the acting seat.
func (t *translator) markCopied(a *action, ref string) {
	mark := func(n string) {
		t.copied[n] = true
		k := fmt.Sprintf("%d|%s", a.seat, n)
		switch {
		case t.copyRef[k] != "":
			t.copyRef[k] = "-" // two copies of one name: no single ref
		case ref != "":
			t.copyRef[k] = ref
		default:
			t.copyRef[k] = fmt.Sprintf("p%d:token:%s", a.seat, n)
		}
	}
	for _, ch := range a.choices {
		if n, ok := strings.CutPrefix(ch.pick, "name:"); ok {
			if x, r := xmageName(n); r == nil {
				mark(x)
			}
		}
	}
	for _, x := range a.targets {
		if n, r := xmageName(x); r == nil && x != "p0" && x != "p1" {
			mark(n)
		}
	}
}

// tailGroup places choices no action consumes (a trigger on the walk to the
// stop step) from step 0; the runner moves them on to the step that asks.
func (t *translator) tailGroup() (*group, *refusal) {
	g := &group{tail: true}
	for _, ch := range t.tailChoices {
		if ch.x >= 0 || ch.mode > 0 {
			return nil, refuse("amount-choice", "unbound %q", ch.pick)
		}
		pick, kind := ch.pick, "any"
		if n, ok := strings.CutPrefix(pick, "name:"); ok {
			if ch.target {
				r, rr := t.targetRef(n)
				if rr != nil {
					return nil, rr
				}
				pick, kind = r, "target"
			} else {
				pick = t.choicePick(n)
			}
		} else if ch.target {
			kind = "target"
		}
		xk := "choice"
		if ch.target {
			xk = "target"
		}
		g.xvals = append(g.xvals, xans{Seat: ch.seat, Kind: xk, Value: pick})
		g.answers = append(g.answers, answer{Kind: kind, Pick: []string{pick}})
	}
	return g, nil
}

// manaSideEffects refuses a scenario whose spells are paid from the pool
// while a card in it cares how mana was made: XMage taps lands to pay, so a
// "whenever a land is tapped for mana" trigger or a land whose mana ability
// does more (Undiscovered Paradise) acts there and not here.
func (t *translator) manaSideEffects(steps []*step) *refusal {
	paid := false
	for _, s := range steps {
		if s.Mana != "" {
			paid = true
			break
		}
	}
	if !paid {
		return nil
	}
	for p := 0; p < 2; p++ {
		for _, ac := range t.setup[p] {
			c, ok := t.lookup(ac.name)
			if !ok {
				continue
			}
			for _, f := range c.Faces {
				if f == nil {
					continue
				}
				for _, tr := range f.Triggers {
					if tr.Mode == "TapsForMana" || tr.Mode == "ManaAdded" {
						return refuse("mana-payment", "%s triggers on mana", ac.name)
					}
				}
				if ac.zone != "battlefield" {
					continue
				}
				for _, sa := range f.Abilities {
					if sa != nil && sa.API == "Mana" && sa.Sub != nil {
						return refuse("mana-payment", "%s's mana ability does more", ac.name)
					}
				}
			}
		}
	}
	return nil
}
