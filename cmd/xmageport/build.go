type abilityPick struct {
	ref   string
	refs  []string // every same-named source, setup order
	index int
	sa    *cards.SA
	face  *cards.Face
}

func normAbility(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	s = strings.ReplaceAll(s, "  ", " ")
	return s
}

// findAbility resolves activateAbility's rule-text prefix to a source and an
// IR ability index, matching it against oraclegen.XMageAbility's selector
// prefixes for every card seat p has.
func (t *translator) findAbility(p int, text string) (*abilityPick, *refusal) {
	x := normAbility(text)
	type cand struct {
		name  string
		perm  bool
		index int
		sa    *cards.SA
		face  *cards.Face
		exact bool
	}
	var cands []cand
	seen := map[string]bool{}
	names := []string{}
	for _, pl := range t.places[p] {
		if !seen[pl.name] {
			seen[pl.name] = true
			names = append(names, pl.name)
		}
	}
	for _, n := range names {
		c, ok := t.lookup(n)
		if !ok {
			continue
		}
		for _, f := range c.Faces {
			if f == nil {
				continue
			}
			m, _ := oraclegen.XMageAbility(f)
			idxs := make([]int, 0, len(m))
			for i := range m {
				idxs = append(idxs, i)
			}
			sort.Ints(idxs)
			for _, i := range idxs {
				pfx := normAbility(m[i])
				if pfx == "" {
					continue
				}
				if strings.HasPrefix(x, pfx) || strings.HasPrefix(pfx, x) {
					cands = append(cands, cand{name: n, perm: len(t.permRefs(p, n)) > 0, index: i, sa: f.Abilities[i], face: f, exact: strings.HasPrefix(x, pfx)})
				}
			}
		}
	}
	if len(cands) == 0 {
		return nil, refuse("ability-unresolved", "%q", text)
	}
	// prefer exact selector matches, then permanents, then the lowest index
	best := cands[:0:0]
	for _, c := range cands {
		if c.exact {
			best = append(best, c)
		}
	}
	if len(best) == 0 {
		best = cands
	}
	var perm []cand
	for _, c := range best {
		if c.perm {
			perm = append(perm, c)
		}
	}
	if len(perm) > 0 {
		best = perm
	}
	srcs := map[string]bool{}
	for _, c := range best {
		srcs[c.name] = true
	}
	if len(srcs) > 1 {
		return nil, refuse("ability-ambiguous", "%q matches %d cards", text, len(srcs))
	}
	c := best[0]
	refs := t.permRefs(p, c.name)
	if len(refs) == 0 {
		refs = t.anyRefs(p, c.name)
	}
	if len(refs) == 0 {
		return nil, refuse("ability-unresolved", "%q source", text)
	}
	return &abilityPick{ref: refs[0], refs: refs, index: c.index, sa: c.sa, face: c.face}, nil
}

// ---- asserts ----

func ip(n int) *int { return &n }

// enumSpelling is the printed spelling of the XMage constants whose name
// drops punctuation.
var enumSpelling = map[string]string{"URZAS": "Urza's"}

func titleEnum(s string) string {
	if i := strings.LastIndex(s, "."); i >= 0 {
		s = s[i+1:]
	}
	if v, ok := enumSpelling[s]; ok {
		return v
	}
	parts := strings.Split(strings.ToLower(s), "_")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, " ")
}

// canCopy reports whether seat p has a setup card that can become a copy of
// another permanent (a face SVar resolving `DB$ Clone`: Clone, Altered Ego,
// Phantasmal Image).
func (t *translator) canCopy(p int) bool {
	for _, pl := range t.places[p] {
		c, ok := t.lookup(pl.name)
		if !ok {
			continue
		}
		for _, f := range c.Faces {
			for _, body := range f.SVars {
				if strings.Contains(body, "DB$ Clone") {
					return true
				}
			}
		}
	}
	return false
}

// copyOnlyRef returns the ref of seat p's copy of the card named n when p's
// only setup cards of that name are off the battlefield (a graveyard or hand
// card its copy effect copied): an assert on the name is about the copy,
// not the setup card. "" when there is no single such copy.
func (t *translator) copyOnlyRef(p int, n string) string {
	if !t.copied[n] || len(t.permRefs(p, n)) > 0 {
		return ""
	}
	if r := t.copyRef[fmt.Sprintf("%d|%s", p, n)]; r != "-" {
		return r
	}
	return ""
}

// castTurns counts the distinct turns seat p casts a card named name on.
func (t *translator) castTurns(p int, name string) int {
	turns := map[int]bool{}
	for _, a := range t.actions {
		if a.kind == "cast" && a.seat == p && sameName(a.card, name) {
			turns[a.turn] = true
		}
	}
	return len(turns)
}

// allOffBattlefield reports whether every setup placement of name for seat p
// is outside the battlefield.
func (t *translator) allOffBattlefield(p int, name string) bool {
	n := 0
	for _, pl := range t.places[p] {
		if sameName(pl.name, name) {
			if pl.zone == "battlefield" {
				return false
			}
			n++
		}
	}
	return n > 0
}

// assertRef maps an asserted card name to a ref: tokens by controller, cards
// by the asserting player's objects first, then the other seat's.
func (t *translator) assertRef(p int, name string) (string, *refusal) {
	n, r := xmageName(name)
	if r != nil {
		return "", r
	}
	if base, tok := isTokenName(n); tok {
		if p < 0 {
			return "", refuse("unmappable-assert", "token %s without player", n)
		}
		return fmt.Sprintf("p%d:token:%s", p, base), nil
	}
	if p >= 0 {
		if rs := t.anyRefs(p, n); len(rs) > 0 {
			if r := t.tokenCopyAssertRefusal(p, n); r != nil {
				return "", r
			}
			if r := t.copyOnlyRef(p, n); r != "" {
				return r, nil
			}
			if t.allOffBattlefield(p, n) && len(rs) > 1 && t.castTurns(p, n) > 1 {
				// two copies waiting in hand/graveyard: XMage's assert binds
				// whichever copy ends up on the battlefield (copies cast on
				// different turns diverge), which a ref cannot name
				return "", refuse("duplicate-name-assert", "%d copies of %s are cast or played during the method", len(rs), n)
			}
			return rs[0], nil
		}
		if t.copied[n] {
			// p's copy of the other seat's card: the copy's own ref
			if r := t.copyRef[fmt.Sprintf("%d|%s", p, n)]; r != "" && r != "-" {
				return r, nil
			}
			return "", refuse("copy-ambiguous-ref", "assert on p%d's copy of %s", p, n)
		}
		_, rs, r := t.otherSeatRefs(p, n, t.anyRefs)
		if r != nil {
			return "", r
		}
		if len(rs) > 0 {
			// A copy of the other seat's card is named for the original
			// but owned by p: bind the assert to p's object, not the original.
			if t.canCopy(p) {
				return fmt.Sprintf("p%d:%s", p, n), nil
			}
			return rs[0], nil
		}
		return "", refuse("assert-not-in-setup", "%s", n)
	}
	rs, many := t.oneSeatRefs(n)
	if !many && len(rs) > 0 {
		for p := 0; p < t.seats(); p++ {
			if r := t.copyOnlyRef(p, n); r != "" {
				return r, nil
			}
		}
	}
	switch {
	case many:
		return "", refuse("unmappable-assert", "%s on both seats", n)
	case len(rs) > 0:
		return rs[0], nil
	}
	return "", refuse("assert-not-in-setup", "%s", n)
}

// runnerLibrary is the filler library the scenario runner deals each seat
// (engine/rules/oracle_run.go).
const runnerLibrary = 40

func countExpect(p int, zone, name string, n int) (*expect, *refusal) {
	nm, r := xmageName(name)
	if r != nil {
		return nil, r
	}
	if nm == "" && n >= runnerLibrary && zone != "battlefield" && zone != "hand" {
		// a seat-wide count this large counts XMage's test library, which
		// is not the runner's 40 filler cards
		return nil, refuse("library-size", "%s count %d", zone, n)
	}
	c := &count{Seat: p, Zone: zone, Name: nm}
	if base, tok := isTokenName(nm); tok {
		c.Name = base
		tr := true
		c.Token = &tr
	}
	return &expect{Count: c, Eq: ip(n)}, nil
}

// countOf is countExpect plus the token-only rule: XMage counts the permanents
// whose name IS the asserted one, but the runner counts the objects whose
// printed name CONTAINS it, so a Role token's name ("Cursed") also counts the
// card that happens to start with it ("Cursed Courtier"). A name no card
// bears and a token script does can only be a token's, so the count is
// restricted to tokens, which keeps the two readings equal.
func (t *translator) countOf(p int, zone, name string, n int) (*expect, *refusal) {
	e, r := countExpect(p, zone, name, n)
	if r != nil || e == nil || e.Count == nil || e.Count.Token != nil || e.Count.Name == "" {
		return e, r
	}
	if _, isCard := t.lookup(e.Count.Name); isCard {
		return e, r
	}
	for _, c := range t.reg.Tokens {
		if c != nil && len(c.Faces) > 0 && c.Faces[0] != nil && strings.EqualFold(c.Faces[0].Name, e.Count.Name) {
			tr := true
			e.Count.Token = &tr
			break
		}
	}
	return e, r
}

// countNameRefusal is the shape refusal of a positive count asserted by a name
// no object can carry: a permanent an effect renamed (Awakening of Vitu-Ghazi
// turns a land into "Vitu-Ghazi"). The scenario's count matches the printed
// face name, which the rename does not change, so it reads 0 whatever gorge
// did. It is a shape, not a hard refusal: the name may be a token's (Banana)
// or part of a card's (Avacyn for "Avacyn, Angel of Hope") and a count that
// holds then stays covered, so the row refuses only when the run fails a count
// no scenario object could satisfy. A count of 0 is vacuous.
func (t *translator) countNameRefusal(p int, zone, name string, want int) *refusal {
	n, r := xmageName(name)
	if r != nil || n == "" || want == 0 {
		// a count of 0 by a name nothing bears holds whatever gorge did
		return nil
	}
	if _, tok := isTokenName(n); tok {
		return nil
	}
	if _, ok := t.lookup(n); ok {
		return nil
	}
	if t.countNameExpressible(p, zone, n) {
		return nil
	}
	sh := refuse("count-name-not-a-card", "%q is not a card name (a renamed permanent?)", n)
	// only a count that read 0 is evidence of the rename: "Cursed" reading 2
	// (Cursed Courtier and its Cursed Role) is the name matching too much.
	sh.onlyIf = func(fails []string) bool {
		for _, f := range fails {
			if strings.Contains(f, fmt.Sprintf("%q = 0, want", n)) {
				return true
			}
		}
		return false
	}
	return sh
}

// countNameExpressible reports whether the runner's count by name in zone for
// seat p can match an object the scenario puts there. The runner counts an
// object when its printed face name CONTAINS the asserted name, case
// insensitively (engine/rules/oracle_run.go), so a partial card name like
// "Avacyn" counts "Avacyn, Angel of Hope".
//
// A card set up outside the counted zone can still reach it: a permanent in
// hand can be cast onto the battlefield, and any card can be discarded,
// milled or exiled. So for a non-battlefield count every placement is
// expressible, and for a battlefield count a placement is too when its card
// can be a permanent (Awakening of Vitu-Ghazi, an instant, cannot; that is why
// Tomik's "Vitu-Ghazi" remains the rename shape). Tokens exist only on the
// battlefield, so a token script's printed name covers a battlefield count.
// The other seat's setup counts too for a battlefield count (control can
// change). A renamed permanent's new name matches no card and no token, which
// is the shape refused here.
func (t *translator) countNameExpressible(p int, zone, name string) bool {
	ln := strings.ToLower(name)
	for _, pl := range t.places[p] {
		if !strings.Contains(strings.ToLower(pl.name), ln) {
			continue
		}
		if zone != "battlefield" || pl.zone == "battlefield" || t.canBePermanent(pl.name) {
			return true
		}
	}
	if zone != "battlefield" {
		return false
	}
	// The other seat's permanent can be controlled by p (Act of Treason), so
	// a battlefield count by its name is expressible whatever zone it is set
	// up in, as long as it can be a permanent.
	for _, q := range t.otherSeats(p) {
		for _, pl := range t.places[q] {
			if strings.Contains(strings.ToLower(pl.name), ln) && (pl.zone == "battlefield" || t.canBePermanent(pl.name)) {
				return true
			}
		}
	}
	for _, c := range t.reg.Tokens {
		if c == nil || len(c.Faces) == 0 || c.Faces[0] == nil {
			continue
		}
		if strings.Contains(strings.ToLower(c.Faces[0].Name), ln) {
			return true
		}
	}
	return false
}

// canBePermanent reports whether any face of the named card has a permanent
// card type, so a placement of it outside the battlefield can still be counted
// there after it is cast or put onto the battlefield.
func (t *translator) canBePermanent(name string) bool {
	c, ok := t.lookup(name)
	if !ok {
		return false
	}
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		if f.IsCreature() || f.IsArtifact() || f.IsEnchantment() || f.IsLand() || f.IsPlaneswalker() || f.IsBattle() {
			return true
		}
	}
	return false
}

func (t *translator) mapAssert(c call) ([]*expect, *refusal) {
	a := c.Args
	bad := func() ([]*expect, *refusal) { return nil, refuse("unmappable-assert", "%s(%d args)", c.Name, len(a)) }
	switch c.Name {
	case "assertLife":
		p, ok := t.seatOf(a[0])
		n, ok2 := argInt(c, 1)
		if !ok || !ok2 {
			return bad()
		}
		return []*expect{{Life: map[string]int32{pref(p): int32(n)}}}, nil
	case "assertPermanentCount", "assertGraveyardCount", "assertHandCount", "assertExileCount":
		zone := map[string]string{"assertPermanentCount": "battlefield", "assertGraveyardCount": "graveyard",
			"assertHandCount": "hand", "assertExileCount": "exile"}[c.Name]
		switch len(a) {
		case 2:
			if p, ok := t.seatOf(a[0]); ok {
				n, ok := argInt(c, 1)
				if !ok {
					return bad()
				}
				switch zone {
				case "hand":
					return []*expect{{HandSize: map[string]int{pref(p): n}}}, nil
				case "graveyard":
					return []*expect{{GraveyardSize: map[string]int{pref(p): n}}}, nil
				}
				e, r := countExpect(p, zone, "", n)
				return []*expect{e}, r
			}
			// assertExileCount(name, n): owner from setup
			name, ok := argStr(c, 0)
			n, ok2 := argInt(c, 1)
			if !ok || !ok2 {
				return bad()
			}
			ref, r := t.assertRef(-1, name)
			if r != nil {
				return nil, r
			}
			e, r := t.countOf(int(ref[1]-'0'), zone, name, n)
			return []*expect{e}, r
		case 3:
			p, ok := t.seatOf(a[0])
			name, ok2 := argStr(c, 1)
			n, ok3 := argInt(c, 2)
			if !ok || !ok2 || !ok3 {
				return bad()
			}
			if r := t.countNameRefusal(p, zone, name, n); r != nil && t.countShape == nil {
				t.countShape = r
			}
			t.tokenCapShape(zone, n)
			e, r := t.countOf(p, zone, name, n)
			return []*expect{e}, r
		}
		return bad()
	case "assertPowerToughness":
		if len(a) < 4 {
			return bad()
		}
		p, ok := t.seatOf(a[0])
		name, ok2 := argStr(c, 1)
		pw, ok3 := argInt(c, 2)
		tg, ok4 := argInt(c, 3)
		if !ok || !ok2 || !ok3 || !ok4 {
			return bad()
		}
		if len(a) > 4 && a[4].s != "Filter.ComparisonScope.Any" && a[4].s != "Filter.ComparisonScope.All" {
			return bad()
		}
		ref, r := t.assertRef(p, name)
		if r != nil {
			return nil, r
		}
		pt := fmt.Sprintf("%d/%d", pw, tg)
		if nm, rr := xmageName(name); rr == nil {
			if r := t.anyScopePTConflict(p, nm, pt); r != nil {
				return nil, r
			}
			// a mana ability that puts a -0/-1 counter (Wall of Roots) moves
			// the P/T this asserts, and the runner pays from the pool
			if t.manaSource(nm) && !t.manaSourceLand(nm) && t.paysFromPool(nm) && t.manaAbilityPutsCounter(nm) && !t.sourceStatedPaid(nm) {
				t.noteShape(refuse("mana-ability-counter", "%s's mana ability puts a counter that changes its P/T, and the runner pays from the pool", nm))
			}
		}
		return []*expect{{Card: ref, PT: pt}}, nil
	case "assertCounterCount":
		var p = -1
		if q, ok := t.seatOf(a[0]); ok {
			p = q
			a = a[1:]
		}
		if len(a) != 3 || a[0].kind != vStr || a[2].kind != vInt {
			return bad()
		}
		kind := ""
		switch a[1].kind {
		case vIdent:
			kind = strings.TrimPrefix(a[1].s, "CounterType.")
		case vStr:
			kind = a[1].s
		default:
			return bad()
		}
		ref, r := t.assertRef(p, a[0].s)
		if r != nil {
			return nil, r
		}
		if nm, rr := xmageName(a[0].s); rr == nil && t.manaSource(nm) && !t.manaSourceLand(nm) && t.paysFromPool(nm) && t.manaAbilityPutsCounter(nm) && !t.sourceStatedPaid(nm) {
			t.noteShape(refuse("mana-ability-counter", "%s's mana ability puts the %s counter, and the runner pays from the pool", nm, kind))
		}
		if nm, rr := xmageName(a[0].s); rr == nil {
			t.counterReplacedEntry(nm, kind)
		}
		return []*expect{{Card: ref, Counters: map[string]int32{kind: int32(a[2].n)}}}, nil
	case "assertType", "assertSubtype", "assertNotSubtype":
		if len(a) < 2 || a[0].kind != vStr {
			return bad()
		}
		ref, r := t.assertRef(-1, a[0].s)
		if r != nil {
			return nil, r
		}
		e := &expect{Card: ref}
		switch c.Name {
		case "assertSubtype":
			e.Types = []string{titleEnum(a[1].s)}
		case "assertNotSubtype":
			e.NoTypes = []string{titleEnum(a[1].s)}
		default:
			if len(a) != 3 {
				return bad()
			}
			ty := titleEnum(a[1].s)
			switch a[2].kind {
			case vBool:
				if a[2].b {
					e.Types = []string{ty}
				} else {
					e.NoTypes = []string{ty}
				}
			case vIdent:
				if a[2].s == "null" {
					// assertType(name, type, null): XMage checks the type
					// only; null states no subtype to require
					e.Types = []string{ty}
				} else {
					e.Types = []string{ty, titleEnum(a[2].s)}
				}
			default:
				return bad()
			}
		}
		return []*expect{e}, nil
	case "assertAbility":
		if len(a) != 4 {
			return bad()
		}
		p, ok := t.seatOf(a[0])
		name, ok2 := argStr(c, 1)
		if !ok || !ok2 || a[3].kind != vBool {
			return bad()
		}
		cls := a[2].s
		cls = strings.TrimSuffix(cls, ".class")
		kw := keywordAbilities[cls]
		if kw == "" {
			return nil, refuse("ability-assert", "%s", a[2].s)
		}
		ref, r := t.assertRef(p, name)
		if r != nil {
			return nil, r
		}
		e := &expect{Card: ref}
		if a[3].b {
			e.Keywords = []string{kw}
		} else {
			e.NoKeywords = []string{kw}
		}
		return []*expect{e}, nil
	case "assertTapped":
		if len(a) != 2 || a[0].kind != vStr || a[1].kind != vBool {
			return bad()
		}
		ref, r := t.assertRef(-1, a[0].s)
		if r != nil {
			return nil, r
		}
		if a[1].b {
			if r := t.tappedRefusal(a[0].s); r != nil {
				return nil, r
			}
		}
		b := a[1].b
		return []*expect{{Card: ref, Tapped: &b}}, nil
	case "assertTappedCount":
		if len(a) != 3 || a[0].kind != vStr || a[1].kind != vBool || a[2].kind != vInt {
			return bad()
		}
		return t.tappedCount(a[0].s, a[1].b, a[2].n)
	case "assertDamageReceived":
		if len(a) != 3 {
			return bad()
		}
		p, ok := t.seatOf(a[0])
		name, ok2 := argStr(c, 1)
		n, ok3 := argInt(c, 2)
		if !ok || !ok2 || !ok3 {
			return bad()
		}
		ref, r := t.assertRef(p, name)
		if r != nil {
			return nil, r
		}
		d := int32(n)
		return []*expect{{Card: ref, Damage: &d}}, nil
	case "checkStackSize":
		n, ok := argInt(c, len(a)-1)
		if !ok {
			return bad()
		}
		return []*expect{{StackSize: ip(n)}}, nil
	}
	return nil, refuse("unsupported-assert", "%s", c.Name)
}

// ---- emitter ----

type emitter struct {
	t              *translator
	steps          []*step
	turn, stp      int
	holder         int
	maxTurn        int
	attacked       map[int]bool
	declared       map[int]bool
	blocked        map[int]bool
	hasStepExpects bool
	tappedAt       map[string]int // {T}-cost source ref -> turn last tapped
	// passed marks the seats whose priority a step already passed at the
	// current clock: a later check for such a seat would sit in the next step.
	passed [maxSeats]bool
	// entered lists, per seat in action order, the permanents earlier play
	// and cast steps put on the battlefield after setup (a land drop, a mana
	// rock): castMana counts them as mana sources.
	entered [maxSeats][]string
	// sensUsed: payment-sensitive source ref -> turn it last paid a cast
	// (-1 once a flicker made it a new object).
	sensUsed map[string]int
	// cloned: per seat, the permanents that entered as a copy of a
	// payment-sensitive source (source_payment.go).
	cloned [maxSeats][]*sensSource
	// spent: per seat, the mana earlier casts seeded since its last untap.
	spent [maxSeats]spentMana
	// defender is the seat each turn's attack declaration goes at.
	defender map[int]int
}

func (em *emitter) add(s *step) *step {
	em.steps = append(em.steps, s)
	return s
}

func (em *emitter) resolve() {
	em.add(&step{Op: "resolve"})
	em.holder = em.t.active(em.turn)
	em.passed = [maxSeats]bool{}
}

func (em *emitter) note(turn int) {
	if turn > em.maxTurn {
		em.maxTurn = turn
	}
}

// gotoClock emits the steps that bring the game to priority in step s of
// turn tn.
func (em *emitter) gotoClock(tn, s int) *refusal {
	moved := tn != em.turn || s != em.stp
	r := em.gotoClockSteps(tn, s)
	if moved && r == nil {
		em.passed = [maxSeats]bool{}
	}
	return r
}

func (em *emitter) gotoClockSteps(tn, s int) *refusal {
	em.note(tn)
	if tn < em.turn || (tn == em.turn && s < em.stp) {
		return refuse("clock-backwards", "to %d/%s from %d/%s", tn, stepNames[s], em.turn, stepNames[em.stp])
	}
	if tn == em.turn && s == em.stp {
		return nil
	}
	if s == sCleanup || s == sUntap {
		return refuse("no-priority-step", "%s", stepNames[s])
	}
	for em.turn < tn {
		em.turn++
		em.stp = sUpkeep
		em.add(&step{Op: "pass_to", Step: "upkeep", Active: pref(em.t.active(em.turn))})
		em.holder = em.t.active(em.turn)
	}
	if s == em.stp {
		return nil
	}
	act := em.t.active(tn)
	switch s {
	case sDeclareAttackers:
		// no attackers: the defender names any opponent (the next seat)
		em.add(&step{Op: "attack", Seat: act, Attackers: []string{}, Defender: pref((act + 1) % em.t.seats())})
		em.declared[tn] = true
	case sDeclareBlockers:
		if !em.attacked[tn] {
			return refuse("combat-step-without-attackers", "%s on turn %d", stepNames[s], tn)
		}
		def := em.defender[tn]
		if em.t.mayBlock(def) {
			em.add(&step{Op: "block", Seat: def, blockActive: em.t.blockActive(act)})
		} else {
			// no creature to block with: gorge poses no blockers ask
			em.add(&step{Op: "pass_to", Step: stepNames[s], Active: pref(act)})
		}
		em.blocked[tn] = true
	case sCombatDamage, sEndCombat:
		if !em.attacked[tn] {
			return refuse("combat-step-without-attackers", "%s on turn %d", stepNames[s], tn)
		}
		em.add(&step{Op: "pass_to", Step: stepNames[s], Active: pref(act)})
	default:
		if s < sMain1 && tn == 1 {
			return refuse("clock-backwards", "turn 1 %s", stepNames[s])
		}
		em.add(&step{Op: "pass_to", Step: stepNames[s], Active: pref(act)})
	}
	em.stp = s
	em.holder = act
	return nil
}

func (em *emitter) sorcerySpeedCast(name string) bool {
	c, ok := em.t.lookup(name)
	if !ok {
		return true
	}
	for _, f := range c.Faces {
		if f == nil || !sameName(f.Name, name) && len(c.Faces) > 1 {
			continue
		}
		for _, ty := range f.Types {
			if ty == "Instant" {
				return false
			}
		}
		for _, k := range f.Keywords {
			if strings.EqualFold(k, "Flash") {
				return false
			}
		}
		return true
	}
	return true
}

func (em *emitter) castMana(seat int, name string, x int) (string, *refusal) {
	c, ok := em.t.lookup(name)
	if !ok {
		return "", refuse("unknown-card", "%s", name)
	}
	if len(c.Faces) == 0 {
		return "", nil
	}
	cost := cardManaCost(c, name)
	ms := em.t.manaSources(seat, em.entered[seat])
	if ms.spent != "" {
		slots, r := costSlots(cost, x)
		if r != nil {
			return "", r
		}
		if len(slots) > ms.basics {
			return "", refuse("mana-source-payment", "%s may have paid for %s", ms.spent, name)
		}
	}
	if ms.loose || em.t.castsForAlternativeCost(c) {
		ms.loose = true
	}
	return manaFromCostSources(cost, x, ms.srcs, ms.loose)
}

// cardManaCost returns the printed mana cost of the named face.
func cardManaCost(c *cards.Card, name string) string {
	if len(c.Faces) == 0 {
		return ""
	}
	cost := c.Faces[0].ManaCost
	for _, f := range c.Faces {
		if f != nil && sameName(f.Name, name) {
			return f.ManaCost
		}
	}
	return cost
}

// landsPay reports whether untapped lands alone cover the named card's cost.
// A mana conversion, an every-land-type land or an alternative cost can
// change what the lands really pay, so those report true (no refusal).
func (em *emitter) landsPay(seat int, name string) bool {
	c, ok := em.t.lookup(name)
	if !ok || len(c.Faces) == 0 {
		return true
	}
	ms := em.t.manaSources(seat, em.entered[seat])
	if ms.loose || em.t.castsForAlternativeCost(c) {
		return true
	}
	cost := cardManaCost(c, name)
	slots, r := costSlots(cost, 0)
	if r != nil {
		return true
	}
	paid, r := manaFromCostSources(cost, 0, ms.landSrcs, false)
	return r == nil && len(paid) >= len(slots)
}

// staticChangesMana reports whether a static ability of f rewrites mana
// production or payment: mana spent as another type (Mode$ ManaConvert), a
// granted AB$ Mana ability, an every-basic-land-type land, or a granted
// alternative-cost keyword (Evoke, Dash, ...).
func staticChangesMana(f *cards.Face, st *cards.Static) bool {
	if st.Mode == "ManaConvert" {
		return true
	}
	for _, n := range strings.Split(st.Params["AddAbility"], "&") {
		if strings.Contains(f.SVars[strings.TrimSpace(n)], "AB$ Mana") {
			return true
		}
	}
	if strings.Contains(st.Params["AddType"], "AllBasicLandType") {
		return true
	}
	for _, kw := range strings.Split(st.Params["AddKeyword"], "&") {
		if altCostKeyword[strings.TrimSpace(strings.SplitN(kw, ":", 2)[0])] {
			return true
		}
	}
	return false
}

// altCostKeyword names the keywords whose cost replaces the printed mana cost.
var altCostKeyword = map[string]bool{"Evoke": true, "Dash": true, "Flashback": true, "Escape": true,
	"Prowl": true, "Surge": true, "Emerge": true, "Overload": true, "Bestow": true, "Blitz": true,
	"Spectacle": true, "Disturb": true, "Foretell": true, "Plot": true, "Madness": true, "Cleave": true}

// castsForAlternativeCost reports whether the card prints an alternative cost
// (Mode$ AlternativeCost: Cobra Trap, Security Rhox) so its printed mana cost
// is not necessarily what XMage's player paid.
func (t *translator) castsForAlternativeCost(c *cards.Card) bool {
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		for i := range f.Statics {
			if f.Statics[i].Mode == "AlternativeCost" {
				return true
			}
		}
	}
	return false
}

// noteEntered records a played land or a cast noncreature permanent as a
// mana source for later casts. A creature cast this way is summoning sick, so
// it cannot pay (a missing source fails visibly rather than falsely passing).
func (em *emitter) noteEntered(a *action) {
	if a.kind != "play" && (a.kind != "cast" || !em.t.isPermanentCard(a.card) || em.t.isCreatureCard(a.card)) {
		return
	}
	em.entered[a.seat] = append(em.entered[a.seat], a.card)
}

// manaSources collects every mana the seat's untapped setup permanents, plus
// the permanents entered since setup, can make: one entry per mana, holding
// the colours it can be (an any-colour source lists WUBRG). A land with basic
// land types makes those colours; any other permanent contributes its printed
// AB$ Mana abilities' Produced$.
func (t *translator) manaSources(p int, entered []string) *manaSet {
	return t.manaSourcesSkipping(p, entered, nil)
}

// manaSourcesSkipping is manaSources without the named permanents: the
// payment-sensitive sources a cast pays by activating them.
func (t *translator) manaSourcesSkipping(p int, entered []string, skip map[string]bool) *manaSet {
	ms := &manaSet{}
	tapped := map[string]bool{}
	var names []string
	// t.setup, not t.places: a basic land the translator drops from the
	// scenario (poolPaidLands, -droplands) is still a source XMage paid with.
	for _, ac := range t.setup[p] {
		if ac.zone != "battlefield" {
			continue
		}
		if ac.tapped {
			tapped[ac.name] = true
			continue
		}
		for i := 0; i < ac.count; i++ {
			names = append(names, ac.name)
		}
	}
	for _, n := range append(names, entered...) {
		if tapped[n] || skip[n] {
			continue
		}
		nm, r := xmageName(n)
		if r != nil {
			continue
		}
		c, ok := t.lookup(nm)
		if !ok {
			continue
		}
		for _, f := range c.Faces {
			if f == nil || !sameName(f.Name, nm) {
				continue
			}
			for i := range f.Statics {
				if staticChangesMana(f, &f.Statics[i]) {
					ms.loose = true
				}
			}
			land := f.IsLand()
			var basic []byte
			if land {
				for _, ty := range f.Types {
					if col, ok := basicLandColour[ty]; ok {
						basic = append(basic, col)
					}
				}
			}
			if len(basic) > 0 {
				ms.srcs = append(ms.srcs, basic)
				ms.landSrcs = append(ms.landSrcs, basic)
				if f.IsBasic() {
					ms.basics++
				}
				continue
			}
			sas := append(f.ManaAbilities(), f.ManaReflectedAbilities()...)
			for _, sa := range sas {
				if !land && ms.spent == "" && sacrificesItself(sa.Params["Cost"]) {
					ms.spent = nm
				}
				produced := producedMana(sa)
				ms.srcs = append(ms.srcs, produced...)
				if land {
					ms.landSrcs = append(ms.landSrcs, produced...)
				} else if len(produced) > 0 {
					// a non-land permanent's mana ability: the runner seeds
					// its mana into the pool instead of activating it
					ms.nonlandSrc = true
				}
			}
		}
	}
	return ms
}

// manaSet is what a seat's battlefield can pay with at one cast.
type manaSet struct {
	srcs [][]byte // one entry per mana, the colours it can be
	// landSrcs is the subset land sources make, so a playable check that only
	// a non-land mana ability can pay is refused instead of seeded.
	landSrcs [][]byte
	// nonlandSrc is set when a non-land permanent contributes mana: XMage's
	// checkPlayableAbility counts that ability, which the runner never
	// activates.
	nonlandSrc bool
	// spent names the first self-sacrificing / self-exiling non-land mana
	// source (Black Lotus, Lotus Petal, a Treasure): XMage's auto-payment may
	// have used it up and the runner cannot say.
	spent string
	// loose: a permanent changes what mana the seat can make or how it may
	// be spent in a way the printed Produced$ lists cannot show (mana spent
	// as another type, granted mana abilities, an every-land-type land, a
	// granted alternative cost). The seed then keeps every cost slot, as it
	// did before sources were read.
	loose  bool
	basics int // untapped basic lands
}

var basicLandColour = map[string]byte{"Plains": 'W', "Island": 'U', "Swamp": 'B', "Mountain": 'R', "Forest": 'G'}

// sacrificesItself reports whether a Forge ability cost sacrifices or exiles
// its own source.
func sacrificesItself(cost string) bool {
	return strings.Contains(cost, "/CARDNAME>") && (strings.Contains(cost, "Sac<") || strings.Contains(cost, "Exile<"))
}

// producedMana is the mana one activation of a mana ability makes: "Combo W U"
// is one mana of either colour, "W B" is two mana, "Any" and the computed
// forms (Chosen, reflected) are one mana of any colour. Amount$ multiplies it.
func producedMana(sa *cards.SA) [][]byte {
	const anyColour = "WUBRG"
	var one [][]byte
	prod := strings.Fields(sa.Params["Produced"])
	switch {
	case len(prod) == 0 || sa.API == "ManaReflected":
		one = [][]byte{[]byte(anyColour)}
	case prod[0] == "Combo":
		set := ""
		for _, c := range prod[1:] {
			if len(c) == 1 && strings.Contains("WUBRGC", c) {
				set += c
			} else {
				set = anyColour
				break
			}
		}
		if set == "" {
			set = anyColour
		}
		one = [][]byte{[]byte(set)}
	default:
		for _, c := range prod {
			if len(c) == 1 && strings.Contains("WUBRGC", c) {
				one = append(one, []byte(c))
			} else {
				one = append(one, []byte(anyColour))
			}
		}
	}
	n := 1
	if a := sa.Params["Amount"]; a != "" {
		if v, err := strconv.Atoi(a); err == nil && v > 0 {
			n = v
		} else {
			n = 2 // computed amount (X, a count): at least a pair
		}
	}
	var out [][]byte
	for ; n > 0; n-- {
		out = append(out, one...)
	}
	return out
}

// hasOptionalCost reports whether the card has a Mode$ OptionalCost static on
// itself (ValidCard$ Card.Self), gorge's "optionalcost" cast option.
func (em *emitter) hasOptionalCost(name string) bool {
	c, ok := em.t.lookup(name)
	if !ok {
		return false
	}
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		for i := range f.Statics {
			st := &f.Statics[i]
			if st.Mode == "OptionalCost" && st.Params["ValidCard"] == "Card.Self" {
				return true
			}
		}
	}
	return false
}

// hasKeywordPrefix reports whether a face of the card carries a keyword
// starting with prefix ("Offspring:2").
func (em *emitter) hasKeywordPrefix(name, prefix string) bool {
	c, ok := em.t.lookup(name)
	if !ok {
		return false
	}
	var faces []*cards.Face
	for _, f := range c.Faces {
		if f != nil && sameName(f.Name, name) {
			faces = append(faces, f)
		}
	}
	if len(faces) == 0 {
		for _, f := range c.Faces {
			if f != nil {
				faces = append(faces, f)
			}
		}
	}
	for _, f := range faces {
		for _, k := range f.Keywords {
			if strings.HasPrefix(k, prefix) {
				return true
			}
		}
	}
	return false
}

// optionalSacrificeMode is the gorge cast mode of the spell's optional
// sacrifice additional cost: "bargained" for Bargain, "casualty" for
// Casualty N, or "" (engine/rules optional_sacrifice.go's two rows). The
// keyword is the card's own or one a setup permanent its controller controls
// grants to THIS spell (Anhelo, the Painter's AddKeyword$ Casualty:2, which
// matches only the controller's instant and sorcery spells on the stack).
func (em *emitter) optionalSacrificeMode(a *action) string {
	for _, m := range [...]struct{ kw, mode string }{{"Bargain", "bargained"}, {"Casualty", "casualty"}} {
		if em.hasKeywordPrefix(a.card, m.kw) || em.t.setupGrantsKeyword(m.kw, a) {
			return m.mode
		}
	}
	return ""
}

// setupGrantsKeyword reports whether a setup battlefield permanent the caster
// controls has a static that adds a keyword starting with prefix to this
// cast. It honours the static's own Affected$/AffectedZone$ scope and its
// CheckSVar$ gate, so a grant aimed at another card type, another controller,
// the battlefield instead of the stack, or after its once-per-turn use does
// not turn an unrelated setChoice(true) into a cast mode.
func (t *translator) setupGrantsKeyword(prefix string, a *action) bool {
	return t.keywordGrants(prefix, a, false, false)
}

// setupMayGrantKeyword is setupGrantsKeyword for a refusal rather than a
// mapping: a selector or gate word it cannot evaluate (numColorsEQ3, wasCast)
// counts as "may apply", so a grant it cannot rule out is still seen, while a
// type word or controller that excludes the cast still rules it out.
func (t *translator) setupMayGrantKeyword(prefix string, a *action) bool {
	return t.keywordGrants(prefix, a, true, false)
}

// keywordGrants scans the seat's setup battlefield (every setup zone when
// anyZone: a granter that a test casts or copies into play still grants).
func (t *translator) keywordGrants(prefix string, a *action, lenient, anyZone bool) bool {
	castFace := t.castFace(a.card)
	if castFace == nil {
		return false
	}
	for _, ac := range t.setup[a.seat] {
		if ac.zone != "battlefield" && !anyZone {
			continue
		}
		c, ok := t.lookup(ac.name)
		if !ok {
			continue
		}
		for _, f := range c.Faces {
			if f == nil || !sameName(f.Name, ac.name) {
				continue
			}
			for i := range f.Statics {
				st := &f.Statics[i]
				if st.Mode != "Continuous" || !strings.HasPrefix(st.Params["AddKeyword"], prefix) {
					continue
				}
				if !t.affectedZoneStack(st.Params["AffectedZone"]) {
					continue
				}
				if !affectedMayMatchFace(castFace, st.Params["Affected"], lenient) {
					continue
				}
				if !t.staticGateHolds(f, st, a, lenient) {
					continue
				}
				return true
			}
		}
	}
	return false
}

// castFace returns the face of name a cast names: the matching front face,
// or the first face for a one-face card. A face that does not match the cast
// name is never inspected, so a keyword on an MDFC's other face cannot leak
// into the cast.
func (t *translator) castFace(name string) *cards.Face {
	c, ok := t.lookup(name)
	if !ok {
		return nil
	}
	for _, f := range c.Faces {
		if f != nil && sameName(f.Name, name) {
			return f
		}
	}
	for _, f := range c.Faces {
		if f != nil {
			return f
		}
	}
	return nil
}

// affectedZoneStack reports whether an AffectedZone$ value admits the stack.
// An absent value is the battlefield default, so it never reaches a spell.
func (t *translator) affectedZoneStack(zone string) bool {
	zones, all, ok := effects.ParseZones(zone)
	if !ok || zone == "" {
		return false
	}
	if all {
		return true
	}
	return slices.Contains(zones, state.ZStack)
}

// affectedMatchesFace matches one Affected$ alternative against the cast
// face. It understands the type words and controller/cast qualifiers the
// corpus uses on keyword grants; an unknown word fails closed rather than
// granting to every spell. "Card.Artifact+nonLegendary+YouCtrl" is a card
// that is an artifact, not legendary, controlled by the caster, so a word can
// be a type wherever it appears.
func affectedMatchesFace(f *cards.Face, affected string) bool {
	return affectedMayMatchFace(f, affected, false)
}

// affectedMayMatchFace is affectedMatchesFace; lenient lets a word it cannot
// evaluate hold instead of failing closed.
func affectedMayMatchFace(f *cards.Face, affected string, lenient bool) bool {
	for _, alt := range strings.Split(affected, ",") {
		alt = strings.TrimSpace(alt)
		if alt == "" {
			continue
		}
		ok := true
		for _, word := range strings.FieldsFunc(alt, func(r rune) bool { return r == '.' || r == '+' }) {
			word = strings.TrimSpace(word)
			if word == "" {
				continue
			}
			if isAffectedTypeWord(word) {
				if !affectedTypeWord(word, f) {
					ok = false
				}
				continue
			}
			switch word {
			case "YouCtrl", "wasCastByYou", "You", "CastSa":
				// The grant's controller is the caster, so every "you"
				// qualifier holds for this cast.
			case "nonLegendary":
				if f.IsLegendary() {
					ok = false
				}
			default:
				if !lenient {
					ok = false
				}
			}
		}
		if ok {
			return true
		}
	}
	return false
}

// isAffectedTypeWord reports whether word is a card-type selector an Affected$
// value may name.
func isAffectedTypeWord(word string) bool {
	switch strings.ToLower(word) {
	case "card", "instant", "sorcery", "creature", "artifact", "enchantment", "land", "planeswalker", "battle":
		return true
	}
	return false
}

// affectedTypeWord matches one type word of an Affected$ alternative.
func affectedTypeWord(word string, f *cards.Face) bool {
	switch strings.ToLower(word) {
	case "card":
		return true
	case "instant":
		return f.IsInstant()
	case "sorcery":
		return f.IsSorcery()
	case "creature":
		return f.IsCreature()
	case "artifact":
		return f.IsArtifact()
	case "enchantment":
		return f.IsEnchantment()
	case "land":
		return f.IsLand()
	case "planeswalker":
		return f.IsPlaneswalker()
	case "battle":
		return f.IsBattle()
	default:
		return false
	}
}

// staticGateHolds evaluates the once-per-turn CheckSVar$ gate a grant static
// carries. Only the turn-scoped cast count the corpus uses is understood; any
// other gate fails closed, so the translator cannot grant a keyword the game
// might withhold.
func (t *translator) staticGateHolds(f *cards.Face, st *cards.Static, a *action, lenient bool) bool {
	sv := st.Params["CheckSVar"]
	if sv == "" {
		return true
	}
	if st.Params["SVarCompare"] != "EQ0" {
		return lenient
	}
	body, ok := f.SVars[sv]
	if !ok {
		return lenient
	}
	const pfx = "Count$ThisTurnCast_"
	if !strings.HasPrefix(body, pfx) {
		return lenient
	}
	filter := strings.TrimPrefix(body, pfx)
	for _, prev := range t.actions {
		if prev.turn != a.turn || prev.seat != a.seat || prev.src >= a.src || (prev.kind != "cast" && prev.kind != "play") {
			continue
		}
		if pf := t.castFace(prev.card); pf != nil && affectedMayMatchFace(pf, filter, !lenient) {
			return false
		}
	}
	return true
}

// activatedAltCost names a setup battlefield card whose static lets a player
// pay an alternative cost for an activated ability (Bruenor Battlehammer's
// {0} equip), or "".
func (t *translator) activatedAltCost() string {
	for p := 0; p < t.seats(); p++ {
		for _, ac := range t.setup[p] {
			if ac.zone != "battlefield" {
				continue
			}
			c, ok := t.lookup(ac.name)
			if !ok {
				continue
			}
			for _, f := range c.Faces {
				if f == nil {
					continue
				}
				for i := range f.Statics {
					st := &f.Statics[i]
					if st.Mode == "AlternativeCost" && strings.Contains(st.Params["ValidSA"], "Activated") {
						return ac.name
					}
				}
			}
		}
	}
	return ""
}

// kickerCost returns the card's Kicker cost ("R", "1 U"), or "".
func (em *emitter) kickerCost(name string) string {
	c, ok := em.t.lookup(name)
	if !ok {
		return ""
	}
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		for _, k := range f.Keywords {
			if strings.HasPrefix(k, "Kicker:") {
				parts := strings.Split(k, ":")
				return parts[1]
			}
		}
	}
	return ""
}

// priorityTo hands priority to seat: priority passes in seat order, so every
// seat from the holder up to (not including) seat passes once.
func (em *emitter) priorityTo(seat int) {
	for em.holder != seat {
		em.add(&step{Op: "pass", Seat: em.holder})
		em.passed[em.holder] = true
		em.holder = (em.holder + 1) % em.t.seats()
	}
}

func (em *emitter) emit(a *action) (*group, *refusal) {
	t := em.t
	var g *group
	attach := func(s *step, hasTargets bool) *refusal {
		if len(a.choices) == 0 {
			return nil
		}
		g = &group{at: len(em.steps) - 1}
		g.xvals = append(g.xvals, a.xlead...)
		modes := 0
		for _, ch := range a.choices {
			if ch.mode > 0 {
				modes++
			}
			if a.kind == "attack" && !ch.target {
				// XMage chooses the planeswalker an effect puts a creature
				// onto the battlefield attacking; gorge never poses that
				// defender choice, so stating it here would only be dropped
				// and the scenario could not go stale when gorge adds it.
				if n, ok := strings.CutPrefix(ch.pick, "name:"); ok && t.isPlaneswalkerCard(n) {
					return refuse("attack-planeswalker-choice", "%s is chosen as an attacker's defender", n)
				}
			}
			if a.kind == "activate" && modes == 0 && (ch.pick == "yes" || ch.pick == "no") && !ch.target && ch.x < 0 && t.activatedAltCost() != "" {
				return refuse("alt-cost-activation-choice", "%s's alternative cost is elected by a boolean", t.activatedAltCost())
			}
		}
		if a.kind == "cast" && t.copyReplacementOnBattlefield() {
			n := 0
			for _, ch := range a.choices {
				if ch.target {
					n++
				}
			}
			if n >= 2 {
				// each extra copy's "choose new targets" is its own
				// addTarget; the runner cannot place the later ones and its
				// fallback takes the first option, so a known_bug here could
				// never go stale
				return refuse("copy-target-choice", "%d new-target answers on %s with a copy replacement in play", n, a.card)
			}
		}
		if modes > 1 {
			// XMage answers a charm with repeatable modes one setModeChoice
			// per pick; gorge asks it once with a multi-pick
			return refuse("multi-mode-choice", "%d setModeChoice calls on %s", modes, a.card)
		}
		for _, ch := range a.choices {
			seat := ch.seat
			if ch.x >= 0 && a.kind != "cast" && a.kind != "activate" {
				// "X=N" not tied to a spell or ability: a damage-assignment
				// or other amount ask gorge does not pose as a choose.
				return refuse("amount-choice", "setChoice X=%d on %s", ch.x, a.kind)
			}
			pick := ch.pick
			if ch.mode > 0 {
				lbl, r := em.modeLabel(a, ch.mode)
				if r != nil {
					return r
				}
				g.xvals = append(g.xvals, xans{Seat: ch.seat, Kind: "mode", Value: pick})
				g.answers = append(g.answers, answer{Kind: "modes", Pick: []string{lbl}, Seat: &seat})
				continue
			}
			if strings.HasPrefix(pick, "name:") {
				n := strings.TrimPrefix(pick, "name:")
				if ch.target {
					r, rr := t.targetRefN(n, ch.ord)
					if rr != nil {
						return rr
					}
					pick = r
				} else {
					pick = t.choicePickN(n, ch.ord)
				}
			}
			xk := "choice"
			if ch.target {
				xk = "target"
			}
			if !ch.synth {
				g.xvals = append(g.xvals, xans{Seat: ch.seat, Kind: xk, Value: pick})
			}
			if ch.kind != "" {
				g.answers = append(g.answers, answer{Kind: ch.kind, Pick: []string{pick}, Seat: &seat})
			} else if ch.target && !hasTargets {
				g.targets = append(g.targets, pick)
			} else if ch.target {
				g.answers = append(g.answers, answer{Kind: "target", Pick: []string{pick}, Seat: &seat})
			} else if ch.x >= 0 {
				g.answers = append(g.answers, answer{Kind: "choose", Pick: []string{pick}, Seat: &seat})
			} else {
				g.answers = append(g.answers, answer{Kind: "any", Pick: []string{pick}, Seat: &seat})
			}
		}
		return nil
	}
	em.note(a.turn)
	switch a.kind {
	case "cast", "play":
		if r := em.gotoClock(a.turn, a.step); r != nil {
			return nil, r
		}
		sorc := a.kind == "play" || em.t != nil && em.sorcerySpeedCast(a.card)
		if sorc {
			if a.seat != t.active(a.turn) {
				return nil, refuse("sorcery-speed-off-turn", "%s", a.card)
			}
			if a.step != sMain1 && a.step != sMain2 {
				return nil, refuse("sorcery-speed-off-main", "%s at %s", a.card, stepNames[a.step])
			}
			em.resolve()
		}
		em.priorityTo(a.seat)
		var ref string
		var ok bool
		if a.kind == "play" {
			ref, ok = t.castRef(a.seat, a.card, "hand")
		} else {
			ref, ok = t.castRef(a.seat, a.card, "hand", "graveyard", "exile", "library_top", "battlefield")
		}
		if !ok {
			return nil, refuse("cast-not-in-setup", "%s", a.card)
		}
		s := &step{Op: a.kind, Seat: a.seat, Card: ref}
		var payment []*step
		if a.kind == "cast" {
			if len(a.choices) > 0 && !a.choices[0].target && a.choices[0].x < 0 && a.choices[0].mode == 0 &&
				a.choices[0].pick != "yes" && a.choices[0].pick != "no" && em.hasOptionalCost(a.card) {
				// the optional cost's payment is a card (Redemptor
				// Dreadnought exiles one from the graveyard): the cast needs
				// cast_mode optionalcost AND that pick as an answer, where a
				// yes/no election is consumed below
				return nil, refuse("optional-cost-pick", "%s: %s", a.card, a.choices[0].pick)
			}
			if t.playsAllAtOnce(a.card) {
				// two or more cards picked by name and confirmed: a pick and a
				// yes/no per card (a lone pick is a sacrifice or bargain cost)
				yes, picks := 0, 0
				for _, ch := range a.choices {
					switch {
					case ch.target || ch.x >= 0:
					case ch.pick == "yes":
						yes++
					case strings.HasPrefix(ch.pick, "name:"):
						picks++
					}
				}
				if yes >= 2 && picks >= 2 {
					return nil, refuse("play-all-one-ask", "%s: XMage asks a pick and a yes/no per card cast (%d casts), gorge poses one modes ask for the whole set", a.card, yes)
				}
			}
			m, pay, r := em.castManaPaying(a.seat, a.card, takeX(a))
			if r != nil {
				return nil, r
			}
			s.Mana = m
			payment = pay
			// XMage answers Kicker's "pay the kicker?" with the first
			// setChoice after the cast; gorge offers it as a cast mode.
			if kc := em.kickerCost(a.card); kc != "" && len(a.choices) > 0 && !a.choices[0].target &&
				(a.choices[0].pick == "yes" || a.choices[0].pick == "no") {
				if a.choices[0].pick == "yes" {
					km, r := manaFromCostX(kc, takeX(a))
					if r != nil {
						return nil, r
					}
					s.Mana += km
					s.Kicked = true
				}
				a.choices = a.choices[1:]
			}
			em.armCastShapes(a)
			if r := em.optionalKeywordCasts(a, s); r != nil {
				return nil, r
			}
			// XMage answers an OptionalCost static ("As an additional cost to
			// cast this spell, you may ...") with the first setChoice(true);
			// gorge offers it as its own cast option, picked by cast_mode.
			if em.hasOptionalCost(a.card) && len(a.choices) > 0 && !a.choices[0].target &&
				a.choices[0].x < 0 && a.choices[0].mode == 0 &&
				(a.choices[0].pick == "yes" || a.choices[0].pick == "no") {
				if a.choices[0].pick == "yes" {
					s.CastMode = "optionalcost"
				}
				a.choices = a.choices[1:]
			}
			// XMage answers the optional sacrifice cost of Bargain and
			// Casualty ("sacrifice an artifact, enchantment, or token as you
			// cast this spell") with the first setChoice; gorge offers it as
			// the "bargained" / "casualty" cast mode and then asks which
			// permanent to sacrifice, which is the choice after the boolean.
			if em.hasKeywordPrefix(a.card, "Casualty") && em.t.setupGrantsKeyword("Casualty", a) &&
				len(a.choices) > 0 && a.choices[0].pick == "yes" {
				// a printed Casualty plus a granted one is two instances
				// (CR 702.153b): gorge offers one casualty election and
				// one sacrifice, so the second cannot be stated
				return nil, refuse("casualty-second-instance", "%s has printed and granted Casualty", a.card)
			}
			if mode := em.optionalSacrificeMode(a); mode != "" && len(a.choices) > 0 && !a.choices[0].target &&
				a.choices[0].x < 0 && a.choices[0].mode == 0 &&
				(a.choices[0].pick == "yes" || a.choices[0].pick == "no") {
				if a.choices[0].pick == "yes" {
					s.CastMode = mode
				}
				a.choices = a.choices[1:]
			}
			// XMage's pick of a MayPlay alternative cost may follow the
			// spell's addTarget (Force of Will under Boromir): the cast still
			// pays no mana and takes the alternative cast option
			for i, ch := range a.choices {
				if !ch.target && ch.x < 0 && ch.mode == 0 && strings.HasPrefix(ch.pick, "name:Cast with alternative cost") {
					s.CastMode, s.Mana = "alternative", ""
					a.choices = append(a.choices[:i:i], a.choices[i+1:]...)
					break
				}
			}
			if len(a.choices) > 0 && !a.choices[0].target && a.choices[0].x < 0 && a.choices[0].mode == 0 {
				switch p := a.choices[0].pick; {
				case p == "yes" && em.hasKeywordPrefix(a.card, "Offspring"):
					// paying for offspring is a cast option in gorge
					return nil, refuse("offspring-choice", "%s", a.card)
				case p == "no" && em.hasKeywordPrefix(a.card, "Offspring"):
					// "Offspring?" declined: the plain cast gorge offers
					a.choices = a.choices[1:]
				case strings.HasPrefix(p, "name:Cast with alternative cost"):
					// XMage's pick of a MayPlay alternative cost (Demon of
					// Fates' Design: "Pay 3 life"); gorge offers it as its
					// own cast option and the step pays no mana
					s.CastMode, s.Mana = "alternative", ""
					a.choices = a.choices[1:]
				case t.permittingObjectPick(a.seat, a.card, p):
					t.noteShape(refuse("mayplay-source-choice", "%s is cast from a zone and %s is picked as the permitting object", a.card, strings.TrimPrefix(p, "name:")))
				}
			}
			if len(a.targets) == 0 {
				// no explicit target: XMage serves the spell's targets and
				// its triggers' targets from one addTarget queue in the order
				// it asks them, which the runner (placing by step) cannot
				// reproduce
				n, seats, interleaved := 0, map[int]bool{}, false
				for i, ch := range a.choices {
					if ch.target {
						n++
						seats[ch.seat] = true
						if i > 0 && !a.choices[i-1].target && n >= 2 {
							interleaved = true
						}
					}
				}
				if n >= 2 && (len(seats) >= 2 || interleaved) {
					r := refuse("target-queue-order", "%s: %d addTarget calls and no explicit target", a.card, n)
					if len(seats) >= 2 || !eachTargetHasOwnMay(a.choices) {
						return nil, r
					}
					// One seat, every target followed by its own yes/no (a
					// doubled "you may" trigger, Panharmonicon): the queue
					// order is not ambiguous between a spell's target and a
					// trigger's, so play it and refuse only if it fails.
					t.queueShape = r
				}
			}
			trs, r := t.targetRefs(a.targets)
			if r != nil {
				return nil, r
			}
			s.Targets = append(s.Targets, trs...)
		}
		if s.CastMode != "alternative" {
			em.commitPayment(a.seat, payment)
		} else {
			// the alternative cost pays no mana: the activations are not
			// needed and the sources were not stated paid
			for _, st := range payment {
				t.markSourceUnpaid(refName(st.Card))
			}
		}
		em.add(s)
		if a.kind == "cast" {
			em.noteFlicker(a.card, s.Targets)
		}
		if a.kind == "play" {
			em.noteClonedSource(a, ref)
		}
		if r := attach(s, len(s.Targets) > 0); r != nil {
			return nil, r
		}
		em.noteEntered(a)
		if (a.kind == "cast" || a.kind == "play") && t.isCopyCard(a.card) {
			if r := t.copiedTargetRefusal(a); r != nil {
				return nil, r
			}
			if !t.isPermanentCard(a.card) {
				t.markCopied(a, "") // a spell's copies are tokens
			} else {
				t.markCopied(a, ref) // the clone itself is the copy
			}
		}
		if a.kind == "cast" && a.resolveAfter {
			em.resolve()
		}
	case "activate":
		if r := em.gotoClock(a.turn, a.step); r != nil {
			return nil, r
		}
		pick, r := t.findAbility(a.seat, a.ability)
		if r != nil {
			return nil, r
		}
		if t.copied[refName(pick.ref)] {
			return nil, refuse("copy-ambiguous-ref", "activate %s after a copy of it", refName(pick.ref))
		}
		pick.ref = em.untappedSource(pick, a.turn)
		if pick.sa.API == "Mana" {
			return nil, refuse("mana-payment", "mana ability %q", a.ability)
		}
		cost := pick.sa.ParamStr(cards.PKCost)
		sorc := pick.sa.HasParam(cards.PKSorcerySpeed) || pick.sa.HasParam(cards.PKPlaneswalker) || strings.Contains(cost, "LOYALTY")
		if sorc {
			if a.seat != t.active(a.turn) {
				return nil, refuse("sorcery-speed-off-turn", "%q", a.ability)
			}
			em.resolve()
		}
		em.priorityTo(a.seat)
		mana, r := manaFromCostX(cost, takeX(a))
		if r != nil {
			return nil, r
		}
		idx := pick.index
		s := &step{Op: "activate", Seat: a.seat, Card: pick.ref, Mana: mana, AbilityIndex: &idx, XAbility: a.ability}
		trs, r := t.targetRefs(a.targets)
		if r != nil {
			return nil, r
		}
		s.Targets = append(s.Targets, trs...)
		em.add(s)
		if r := attach(s, len(s.Targets) > 0); r != nil {
			return nil, r
		}
		if saCopies(pick.sa) {
			t.markCopied(a, "")
		}
	case "wait":
		if r := em.gotoClock(a.turn, a.step); r != nil {
			return nil, r
		}
		em.resolve()
	case "attack":
		if a.turn > em.turn {
			if r := em.gotoClock(a.turn, sUpkeep); r != nil {
				return nil, r
			}
		}
		if a.turn < em.turn || (a.turn == em.turn && em.stp >= sDeclareAttackers) {
			return nil, refuse("clock-backwards", "attack on turn %d", a.turn)
		}
		if a.seat != t.active(a.turn) {
			return nil, refuse("bad-args", "attack by non-active player")
		}
		used := map[string]int{}
		var refs []string
		for _, n := range a.attackers {
			if t.copied[n] {
				return nil, refuse("copy-ambiguous-ref", "attack with %s after a copy of it", n)
			}
			rs := t.permRefs(a.seat, n)
			k := used[n]
			used[n]++
			if k >= len(rs) {
				return nil, refuse("attacker-not-in-setup", "%s", n)
			}
			refs = append(refs, rs[k])
		}
		s := em.add(&step{Op: "attack", Seat: a.seat, Attackers: refs, Defender: pref(a.defender)})
		em.declared[a.turn] = true
		em.stp = sDeclareAttackers
		em.holder = a.seat
		if r := attach(s, false); r != nil {
			return nil, r
		}
	case "block":
		if !em.declared[a.turn] || em.turn != a.turn || em.stp > sDeclareAttackers {
			return nil, refuse("clock-backwards", "block on turn %d", a.turn)
		}
		if t.seats() > 2 && a.seat != em.defender[a.turn] {
			// only the attacked player declares blockers
			return nil, refuse("multi-seat-shape", "block by p%d, attack goes at p%d", a.seat, em.defender[a.turn])
		}
		atk := t.attackRefs(a.turn)
		used := map[string]int{}
		var blocks [][2]string
		for _, b := range a.blocks {
			rs := t.permRefs(a.seat, b[0])
			k := used[b[0]]
			used[b[0]]++
			if k >= len(rs) {
				return nil, refuse("blocker-not-in-setup", "%s", b[0])
			}
			ar := ""
			for _, x := range atk {
				if refName(x) == b[1] || sameName(refName(x), b[1]) {
					ar = x
					break
				}
			}
			if ar == "" {
				return nil, refuse("bad-args", "block names non-attacker %s", b[1])
			}
			blocks = append(blocks, [2]string{rs[k], ar})
		}
		s := em.add(&step{Op: "block", Seat: a.seat, Blocks: blocks, blockActive: t.blockActive(t.active(a.turn))})
		em.blocked[a.turn] = true
		em.stp = sDeclareBlockers
		em.holder = t.active(a.turn)
		if r := attach(s, false); r != nil {
			return nil, r
		}
	case "check":
		if r := em.gotoClock(a.turn, a.step); r != nil {
			if a.playCheck != nil {
				// the check names a step the runner cannot stop in with a
				// player on priority (combat without attackers, a clock
				// that has already moved past it, ...)
				return nil, refuse("playable-check", "%s", r.Detail)
			}
			return nil, r
		}
		xs := a.expects
		if a.playCheck != nil {
			off, r := em.t.playableOffer(a.seat, a.src, a.playCheck.want, a.playCheck.text)
			if r != nil {
				return nil, r
			}
			want := a.playCheck.want
			xs = []*expect{{Offered: off, Want: &want}}
		}
		if len(em.steps) == 0 {
			// anchor on the setup decision: the runner's first priority
			// decision already lists the hand's plays and casts. Never pass
			// the checking seat's own priority here: that ends the step the
			// check is about.
			em.add(&step{Op: "pass_to", Decision: "priority"})
		}
		if a.playCheck != nil {
			// the offered check reads the priority holder, so the expect
			// must ride a step that leaves the checking seat on priority.
			if em.holder != a.seat && em.passed[a.seat] {
				// the seat's priority was already passed at this clock (the
				// test states one player's checks around the other's), so
				// the runner's pass would end the step the check is about
				em.t.noteShape(refuse("playable-check-order", "%s's priority at %s of turn %d was passed by an earlier check", pref(a.seat), stepNames[em.stp], em.turn))
			}
			em.priorityTo(a.seat)
		}
		if a.playCheck != nil && a.playCheck.want && len(xs) == 1 && xs[0].Offered != nil && xs[0].Offered.Kind == "cast" {
			// gorge lists a cast option only while the pool already holds its
			// cost, and the runner has no land-tapping autopay: XMage's
			// checkPlayableAbility counts the lands, so float the cost on the
			// step that carries the offered expect.
			name := refName(xs[0].Offered.Card)
			if ms := em.t.manaSources(a.seat, em.entered[a.seat]); ms.nonlandSrc && !em.landsPay(a.seat, name) {
				// The check can only be true because of a non-land mana
				// ability (Alena, Kessig Trapper's {T}: Add {R}); seeding
				// that mana into the pool proves nothing about the ability
				// and would hide the defect the check is about.
				return nil, refuse("offered-check-mana-source", "%s needs a non-land mana ability", name)
			}
			m, r := em.castMana(a.seat, name, 0)
			if r != nil {
				return nil, refuse("playable-check", "cost of %s: %s", xs[0].Offered.Card, r.Detail)
			}
			if c, ok := em.t.lookup(name); ok && printsAltCast(c) {
				// XMage's check is true when ANY cast of the card is payable
				// (the face-down {3} of a Willbender with Swamps, Cyclonic
				// Rift's {6}{U} overload), so the pool holds what the lands
				// can make, not only the plain cost
				if lp := landPool(em.t.manaSources(a.seat, em.entered[a.seat]).landSrcs); len(lp) > len(m) {
					m = lp
				}
			}
			if m != "" {
				em.add(&step{Op: "mana", Seat: a.seat, Mana: m})
			}
		}
		last := em.steps[len(em.steps)-1]
		if last.Op == "activate" && a.playCheck == nil {
			// XMage's check sees the game after the ability resolved; the
			// expect rides the activation step, before it does
			em.t.noteShape(refuse("check-before-ability-resolves", "a check follows %s's activation with no resolve", last.Card))
		}
		last.Expect = append(last.Expect, xs...)
		em.hasStepExpects = true
	}
	return g, nil
}

// mayBlock reports whether seat p has a creature that could be asked to
// block (setup battlefield or a cast creature card).
func (t *translator) mayBlock(p int) bool {
	isCreature := func(n string) bool {
		c, ok := t.lookup(n)
		if !ok {
			return true
		}
		for _, f := range c.Faces {
			if f == nil {
				continue
			}
			for _, ty := range f.Types {
				if ty == "Creature" {
					return true
				}
			}
		}
		return false
	}
	for _, pl := range t.places[p] {
		if pl.zone == "battlefield" && isCreature(pl.name) {
			return true
		}
	}
	for n := range t.castRefs[p] {
		if isCreature(n) {
			return true
		}
	}
	return false
}

func refName(ref string) string {
	i := strings.IndexByte(ref, ':')
	n := ref[i+1:]
	if j := strings.LastIndexByte(n, '#'); j >= 0 {
		n = n[:j]
	}
	return n
}

// attackRefs returns the refs declared as attackers on turn tn.
func (t *translator) attackRefs(tn int) []string {
	// the emitter wrote them on the attack step; find it via actions
	for _, a := range t.actions {
		if a.kind == "attack" && a.turn == tn {
			used := map[string]int{}
			var out []string
			for _, n := range a.attackers {
				rs := t.permRefs(a.seat, n)
				k := used[n]
				used[n]++
				if k < len(rs) {
					out = append(out, rs[k])
				}
			}
			return out
		}
	}
	return nil
}

// stopAt emits the steps for setStopAt(tn, s). XMage pauses AFTER it has
// played step s (mage/game/turn/Phase.java: playStep, then
// checkStopOnStepOption), so the asserted state is the END of step s: its
// actions done and its stack resolved.
func (em *emitter) stopAt(tn, s int) *refusal {
	em.note(tn)
	type tgt struct {
		turn, step int
		resolve    bool
	}
	g := tgt{tn, s, true}
	switch s {
	case sUntap:
		g = tgt{tn, sUpkeep, false}
	case sDeclareAttackers:
		if !em.declared[tn] {
			g = tgt{tn, sBeginCombat, true}
		}
	case sDeclareBlockers:
		if !em.attacked[tn] {
			g = tgt{tn, sBeginCombat, true}
		}
	case sCombatDamage:
		// gorge has one step value for both damage steps: stop past both
		if em.attacked[tn] {
			g = tgt{tn, sEndCombat, false}
		} else {
			g = tgt{tn, sBeginCombat, true}
		}
	case sEndCombat:
		if !em.attacked[tn] {
			g = tgt{tn, sBeginCombat, true}
		}
	case sCleanup:
		// the end of cleanup is the next turn's beginning
		g = tgt{tn + 1, sUpkeep, false}
	}
	if g.turn == 1 && g.step < sMain1 {
		g.step = sMain1
	}
	if em.turn == g.turn && g.step < em.stp {
		g.step = em.stp
	}
	if g.turn < em.turn {
		return refuse("clock-backwards", "stop at %d/%s", tn, stepNames[s])
	}
	if r := em.gotoClock(g.turn, g.step); r != nil {
		return r
	}
	if g.resolve {
		em.resolve()
	}
	return nil
}

// takeX returns the action's announced X (the first setChoice "X=N" it
// consumes), or -1. The choice stays queued: gorge poses X as a choose ask.
func takeX(a *action) int {
	for _, ch := range a.choices {
		if ch.x >= 0 {
			return ch.x
		}
	}
	return -1
}

// manaSource reports whether the named card is a permanent XMage can tap to
// pay a cost that the runner pays from the pool instead: a land (basic lands
// carry their mana ability intrinsically, not as a printed AB$ Mana) or a face
// with a mana ability.
func (t *translator) manaSource(name string) bool {
	nm, r := xmageName(name)
	if r != nil {
		return false
	}
	c, ok := t.lookup(nm)
	if !ok {
		return false
	}
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		if f.IsLand() || f.HasManaAbility() {
			return true
		}
	}
	return false
}

// manaSourceLand reports whether any face of the named card is a land. Lands
// have an intrinsic mana ability (basic lands carry no printed AB$ Mana), so
// a "tapped" assertion on one always refuses.
func (t *translator) manaSourceLand(name string) bool {
	nm, r := xmageName(name)
	if r != nil {
		return false
	}
	c, ok := t.lookup(nm)
	if !ok {
		return false
	}
	for _, f := range c.Faces {
		if f != nil && f.IsLand() {
			return true
		}
	}
	return false
}

// sourceSeat returns the seat that put the named permanent on the
// battlefield, so a non-land mana source only refuses for a cast/activation
// its controller could have paid for.
func (t *translator) sourceSeat(name string) (int, bool) {
	for p := 0; p < t.seats(); p++ {
		for _, ac := range t.setup[p] {
			if ac.zone == "battlefield" && ac.name == name {
				return p, true
			}
		}
	}
	return 0, false
}

// paysFromPool reports whether the method casts or activates something the
// source's controller could pay for. XMage taps a mana source only while
// paying such a cost; a source tapped for a non-mana {T} ability, crew or
// convoke is not this class (brief 10) and must keep generating. When the
// controller is not in setup (a token), any cast/activation counts: refusing
// is the direction that cannot hide a false fail.
func (t *translator) paysFromPool(name string) bool {
	nm, r := xmageName(name)
	if r != nil {
		return false
	}
	seat, known := t.sourceSeat(nm)
	for _, a := range t.actions {
		if a.kind != "cast" && a.kind != "activate" {
			continue
		}
		if !known || a.seat == seat {
			return true
		}
	}
	return false
}

// tappedRefusal refuses an assertion that the named permanent is tapped when
// the runner would leave it untapped: a step's mana is injected into the pool,
// so a source XMage tapped to pay for a spell or ability never taps here.
// assertTapped and assertTappedCount both call it, so the two cannot drift.
// The caller owns the assert direction: a "not tapped" expectation matches the
// runner and must still generate.
func (t *translator) tappedRefusal(name string) *refusal {
	if !t.manaSource(name) {
		return nil
	}
	// A land always refuses: that is tappedCount's existing fallback, which
	// the brief allows. A non-land mana source refuses only when the method
	// casts or activates something its controller could pay for with it; a
	// mana dork tapped by a non-mana ability (crew, convoke) still generates.
	if t.manaSourceLand(name) || t.paysFromPool(name) {
		return refuse("tapped-land-count", "%s", name)
	}
	return nil
}

// tappedCount maps assertTappedCount(name, tapped, n): exactly n permanents
// named name have isTapped()==tapped. Expressible per object only when n is
// 0 (all have the other state) or every known instance. A mana source
// refuses only when the assertion expects an instance tapped: the runner pays
// from the pool, so a source XMage tapped for mana stays untapped, while an
// "untapped" expectation is what the runner already produces.
func (t *translator) tappedCount(name string, tapped bool, n int) ([]*expect, *refusal) {
	nm, r := xmageName(name)
	if r != nil {
		return nil, r
	}
	// n==0 inverts the predicate: "0 tapped" expects all untapped, "0
	// untapped" expects all tapped.
	wantsTapped := tapped
	if n == 0 {
		wantsTapped = !tapped
	}
	if wantsTapped {
		if r := t.tappedRefusal(nm); r != nil {
			return nil, r
		}
	}
	refs := append(t.permRefs(0, nm), t.permRefs(1, nm)...)
	if len(refs) == 0 {
		return nil, refuse("assert-not-in-setup", "%s", nm)
	}
	want := tapped
	switch n {
	case 0:
		want = !tapped
	case len(refs):
	default:
		return nil, refuse("tapped-subset", "assertTappedCount %s %d of %d", nm, n, len(refs))
	}
	var out []*expect
	for _, ref := range refs {
		b := want
		out = append(out, &expect{Card: ref, Tapped: &b})
	}
	return out, nil
}

// modeLabel names the n-th (1-based) Charm mode of the spell a casts as the
// label gorge's modes ask offers (effects.CharmModeLabel over Choices$
// order). Only a cast whose spell ability (or its first sub) is a Charm
// maps; anything else refuses.
func (em *emitter) modeLabel(a *action, n int) (string, *refusal) {
	if a.kind != "cast" {
		return "", refuse("mode-choice", "setModeChoice on %s", a.kind)
	}
	c, ok := em.t.lookup(a.card)
	if !ok {
		return "", refuse("unknown-card", "%s", a.card)
	}
	for _, f := range c.Faces {
		if f == nil || !sameName(f.Name, a.card) && len(c.Faces) > 1 {
			continue
		}
		for sa := f.SpellAbility(); sa != nil; sa = sa.Sub {
			if sa.API != "Charm" {
				continue
			}
			modes := effects.CharmOf(sa).Modes
			if n > len(modes) {
				return "", refuse("mode-choice", "mode %d of %d", n, len(modes))
			}
			return effects.CharmModeLabel(cards.ResolveSVar(f.SVars, modes[n-1]), modes[n-1]), nil
		}
	}
	return "", refuse("mode-choice", "no Charm on %s", a.card)
}

// untappedSource picks which same-named source an activation uses. XMage
// activates the first one that can pay, so a {T} ability already used by
// an untapped-since copy moves on to the next copy (two Rushwood
// Herbalists regenerating twice in one turn).
func (em *emitter) untappedSource(pick *abilityPick, turn int) string {
	if !hasTapCost(pick.sa.ParamStr(cards.PKCost)) {
		return pick.ref
	}
	if em.tappedAt == nil {
		em.tappedAt = map[string]int{}
	}
	seat := int(pick.ref[1] - '0')
	free := func(ref string) bool {
		k, ok := em.tappedAt[ref]
		if !ok {
			return true
		}
		for u := k + 1; u <= turn; u++ {
			if em.t.active(u) == seat {
				return true
			}
		}
		return false
	}
	ref := pick.ref
	for _, r := range pick.refs {
		if free(r) {
			ref = r
			break
		}
	}
	em.tappedAt[ref] = turn
	return ref
}

func hasTapCost(cost string) bool {
	for _, tok := range strings.Fields(cost) {
		if tok == "T" {
			return true
		}
	}
	return false
}

// isCopyCard reports whether casting name makes a copy of a permanent: a
// Clone or CopyPermanent ability, direct or through an SVar (an ETB
// "enter as a copy" replacement).
func (t *translator) isCopyCard(name string) bool {
	c, ok := t.lookup(name)
	if !ok {
		return false
	}
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		for _, sa := range f.Abilities {
			if sa != nil && (sa.API == "Clone" || sa.API == "CopyPermanent") {
				return true
			}
		}
		for _, v := range f.SVars {
			if strings.Contains(v, "$ Clone") || strings.Contains(v, "$ CopyPermanent") {
				return true
			}
		}
	}
	return false
}

// isPermanentCard reports whether name's front face is a permanent card.
func (t *translator) isPermanentCard(name string) bool {
	c, ok := t.lookup(name)
	if !ok || len(c.Faces) == 0 || c.Faces[0] == nil {
		return true
	}
	for _, ty := range c.Faces[0].Types {
		if ty == "Instant" || ty == "Sorcery" {
			return false
		}
	}
	return true
}

// isCreatureCard reports whether the named card's front face is a creature.
func (t *translator) isCreatureCard(name string) bool {
	c, ok := t.lookup(name)
	return ok && len(c.Faces) > 0 && c.Faces[0] != nil && c.Faces[0].IsCreature()
}

// isPlaneswalkerCard reports whether any face of the named card is a
// planeswalker.
func (t *translator) isPlaneswalkerCard(name string) bool {
	c, ok := t.lookup(name)
	if !ok {
		return false
	}
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		for _, ty := range f.Types {
			if ty == "Planeswalker" {
				return true
			}
		}
	}
	return false
}

// saCopies reports whether activating sa makes a permanent copy.
func saCopies(sa *cards.SA) bool {
	for x := sa; x != nil; x = x.Sub {
		if x.API == "Clone" || x.API == "CopyPermanent" {
			return true
		}
	}
	return false
}

// copiedTargetRefusal refuses a copy action whose own targets name a card its
// setChoice picks copy (Clone's "Craw Wurm" followed by addTarget "Craw
// Wurm" for a trigger of the permanent that entered): the target is the copy,
// which the caster controls, while setup names only the original, so the ref
// the targets resolved to before the copy existed names the wrong object.
func (t *translator) copiedTargetRefusal(a *action) *refusal {
	copiedNames := map[string]bool{}
	for _, ch := range a.choices {
		if n, ok := strings.CutPrefix(ch.pick, "name:"); ok && !ch.target {
			if x, r := xmageName(n); r == nil {
				copiedNames[x] = true
			}
		}
	}
	named := append([]string(nil), a.targets...)
	for _, ch := range a.choices {
		if n, ok := strings.CutPrefix(ch.pick, "name:"); ok && ch.target {
			named = append(named, n)
		}
	}
	for _, x := range named {
		if n, r := xmageName(x); r == nil && copiedNames[n] {
			return refuse("copy-ambiguous-ref", "target %s names the card %s copies", n, a.card)
		}
	}
	return nil
}

// markCopied records the names a copy action's choices and targets name:
// from here on that name may belong to two permanents. The copy itself is
// the cast card (ref) or, for an ability, a token of the acting seat.
func (t *translator) markCopied(a *action, ref string) {
	mark := func(n string) {
		t.copied[n] = true
		k := fmt.Sprintf("%d|%s", a.seat, n)
		switch {
		case t.copyRef[k] != "":
			t.copyRef[k] = "-" // two copies of one name: no single ref
		case ref != "":
			t.copyRef[k] = ref
		default:
			t.copyRef[k] = fmt.Sprintf("p%d:token:%s", a.seat, n)
		}
	}
	for _, ch := range a.choices {
		if n, ok := strings.CutPrefix(ch.pick, "name:"); ok {
			if x, r := xmageName(n); r == nil {
				mark(x)
			}
		}
	}
	for _, x := range a.targets {
		if n, r := xmageName(x); r == nil && !isSeatRef(x) {
			mark(n)
		}
	}
}

// tailGroup places choices no action consumes (a trigger on the walk to the
// stop step) from step 0; the runner moves them on to the step that asks.
func (t *translator) tailGroup() (*group, *refusal) {
	g := &group{tail: true}
	for _, ch := range t.tailChoices {
		if ch.x >= 0 || ch.mode > 0 {
			return nil, refuse("amount-choice", "unbound %q", ch.pick)
		}
		pick, kind := ch.pick, "any"
		if n, ok := strings.CutPrefix(pick, "name:"); ok {
			if ch.target {
				r, rr := t.targetRefN(n, ch.ord)
				if rr != nil {
					return nil, rr
				}
				pick, kind = r, "target"
			} else {
				pick = t.choicePickN(n, ch.ord)
			}
		} else if ch.target {
			kind = "target"
		}
		xk := "choice"
		if ch.target {
			xk = "target"
		}
		g.xvals = append(g.xvals, xans{Seat: ch.seat, Kind: xk, Value: pick})
		g.answers = append(g.answers, answer{Kind: kind, Pick: []string{pick}})
	}
	return g, nil
}

// manaSideEffects refuses a scenario whose spells are paid from the pool
// while a card in it cares how mana was made: XMage taps lands to pay, so a
// "whenever a land is tapped for mana" trigger or a land whose mana ability
// does more (Undiscovered Paradise) acts there and not here.
func (t *translator) manaSideEffects(steps []*step) *refusal {
	paid := false
	for _, s := range steps {
		if s.Mana != "" {
			paid = true
			break
		}
	}
	if !paid {
		return nil
	}
	seen := map[string]bool{}
	check := func(name string) *refusal {
		if seen[name] {
			return nil
		}
		seen[name] = true
		c, ok := t.lookup(name)
		if !ok {
			return nil
		}
		return manaSideEffect(c, name)
	}
	for p := 0; p < t.seats(); p++ {
		for _, ac := range t.setup[p] {
			if ac.zone != "battlefield" {
				// only battlefield permanents have active triggered or
				// static abilities: a card merely in hand or in a graveyard
				// cannot trigger on mana or tax its own mana abilities
				continue
			}
			if r := check(ac.name); r != nil {
				return r
			}
		}
	}
	// A land played or a permanent cast during the method is on the
	// battlefield only for the pool-paid steps emitted after it (Thran
	// Portal's mana abilities taxed in chromaticLanternCostInteraction): a
	// later cast or activation that pays nothing from the pool never uses it.
	for _, a := range t.actions {
		switch a.kind {
		case "play":
		case "cast":
			if !t.isPermanentCard(a.card) {
				continue
			}
		default:
			continue
		}
		later := false
		for i := a.endAt; i < len(steps); i++ {
			if steps[i].Mana != "" {
				later = true
				break
			}
		}
		if !later {
			continue
		}
		if r := check(a.card); r != nil {
			return r
		}
	}
	return nil
}

// replicateChoiceRefusal refuses a spell cast whose replicate count XMage
// states as a boolean. XMage's "Yes, replicate / No, only once" answers are
// gorge's cast-flow KChoose count ask (0..N), not a yes/no, so the stated
// choices are never consumed and the spell is cast once (Djinn Illuminatus,
// Threefold Signal). A grant reaches a cast by its own Affected$ scope, not by
// the cast's card type, so each cast is asked of the grants that may apply to
// it; gorge also never offers the replicated mode for a granted keyword, so a
// corrected election cannot be stated either.
func (t *translator) replicateChoiceRefusal() *refusal {
	for _, a := range t.actions {
		if a.kind != "cast" || len(a.choices) == 0 || !t.setupMayGrantKeyword("Replicate", a) {
			continue
		}
		for _, ch := range a.choices {
			if p := strings.ToLower(ch.pick); p == "yes" || p == "no" {
				return refuse("replicate-choice", "%s replicate count", a.card)
			}
		}
	}
	return nil
}

// copyReplacementOnBattlefield reports a setup battlefield permanent that
// changes how many copies of a spell are made (Twinning Staff's Event$ CopySpell).
func (t *translator) copyReplacementOnBattlefield() bool {
	for p := 0; p < t.seats(); p++ {
		for _, ac := range t.setup[p] {
			if ac.zone != "battlefield" {
				continue
			}
			c, ok := t.lookup(ac.name)
			if !ok {
				continue
			}
			for _, f := range c.Faces {
				if f == nil {
					continue
				}
				for _, r := range f.Repls {
					if r.Event == "CopySpell" {
						return true
					}
				}
			}
		}
	}
	return false
}

// manaSideEffect refuses one battlefield card that cares how mana was made.
func manaSideEffect(c *cards.Card, name string) *refusal {
	for _, f := range c.Faces {
		if f == nil {
			continue
		}
		for _, tr := range f.Triggers {
			if tr.Mode == "TapsForMana" || tr.Mode == "ManaAdded" {
				return refuse("mana-payment", "%s triggers on mana", name)
			}
		}
		for i := range f.Statics {
			st := &f.Statics[i]
			if st.Mode == "RaiseCost" && strings.Contains(st.Params["ValidSpell"], "Activated.ManaAbility") {
				// Thran Portal: its mana abilities cost 1 life, paid
				// by tapping it, which the pool never does
				return refuse("mana-ability-cost", "%s taxes its own mana abilities", name)
			}
			if strings.Contains(st.Params["AddKeyword"], "PayLifeInsteadOf") {
				// K'rrik: XMage's choice to pay life for {B}
				return refuse("pay-life-instead-of-mana", "%s lets life pay for mana", name)
			}
		}
		for _, sa := range f.Abilities {
			if sa == nil || sa.API != "Mana" {
				continue
			}
			if strings.Contains(sa.ParamStr(cards.PKCost), "Sac<") {
				// Bolg's Company: "{T}, Sacrifice another Goblin: Add
				// {B}{R}". Paying the spell from the pool never activates
				// the ability, so the sacrifice and the choice of Goblin
				// are skipped.
				return refuse("mana-ability-cost", "%s sacrifices a permanent for mana", name)
			}
			if sa.Sub != nil || sa.ParamStr(cards.PKTriggersWhenSpent) != "" {
				// a sub-ability, or "when you spend this mana ..."
				return refuse("mana-payment", "%s's mana ability does more", name)
			}
		}
	}
	return nil
}

// eachTargetHasOwnMay reports whether every target choice of cs is directly
// followed by a yes/no answer: each addTarget answers a trigger's target and
// its own optional ask, not a spell's target ahead of a trigger's.
func eachTargetHasOwnMay(cs []choice) bool {
	for i, ch := range cs {
		if !ch.target {
			continue
		}
		if i+1 >= len(cs) {
			return false
		}
		nx := cs[i+1]
		if nx.target || nx.x >= 0 || nx.mode != 0 || (nx.pick != "yes" && nx.pick != "no") {
			return false
		}
	}
	return true
}
