// symptom is a class's one-line symptom.
func symptom(c Class) string {
	switch c.What {
	case "options":
		return fmt.Sprintf("gorge and Forge offer different %s options", c.Kind)
	case "answer-missing":
		return fmt.Sprintf("Forge's %s answer is not on gorge's list", c.Kind)
	case "snapshot":
		return fmt.Sprintf("gorge's state differs from Forge's at %s", c.Field)
	case "kind":
		return fmt.Sprintf("gorge poses a different decision where Forge asks %s", c.Kind)
	case "terminal":
		return "gorge ends the game differently"
	case "error":
		return fmt.Sprintf("gorge errors at a %s decision", c.Kind)
	}
	return fmt.Sprintf("%s difference at %s", c.What, c.Kind)
}

// shortest is the class's finding with the shortest record prefix: the lowest
// log offset, then game.
func shortest(c Class) Divergence {
	var best Divergence
	for i, s := range c.Signatures {
		f := s.Findings[0]
		for _, g := range s.Findings {
			if g.Offset < f.Offset {
				f = g
			}
		}
		if i == 0 || f.Offset < best.Offset || (f.Offset == best.Offset && f.Game < best.Game) {
			best = f
		}
	}
	return best
}

// fshadowBrief is design section 5's brief template for one class: Suspect and
// Repro first, then the evidence. A harness class is a follower ticket in
// gorge-compliance.
func fshadowBrief(c Class, all *Census, r Ranker) string {
	repo, prim := "gorge", c.Primitive
	if c.Harness {
		repo = "gorge-compliance"
	}
	suspect := genericSuspect(prim)
	if r.Suspect != nil {
		suspect = r.Suspect(prim)
	}
	s := shortest(c)
	repro := s.Repro
	switch {
	case repro != "":
	case s.Record != "":
		repro = fmt.Sprintf("replay the gorge record prefix %s (gorge-match-1 with Chance) to log offset %d", s.Record, s.Offset)
	default:
		repro = fmt.Sprintf("re-shadow %s (forge-shadow-1) with `xengine fshadow` to log offset %d", s.Log, s.Offset)
	}
	games, decks, names := map[string]bool{}, map[string]bool{}, map[string]bool{}
	var sigs []string
	for _, sg := range c.Signatures {
		sigs = append(sigs, sg.SHA12)
		for _, n := range sg.Cards {
			names[n] = true
		}
		for _, f := range sg.Findings {
			games[f.Game] = true
			for _, d := range f.Decks {
				decks[d] = true
			}
		}
	}
	var others []string
	same := all.Classes
	if c.Harness {
		same = all.Harness
	}
	for _, o := range same {
		if o.Primitive != prim {
			others = append(others, o.Primitive)
		}
	}
	others = uniqSorted(others)
	var b strings.Builder
	fmt.Fprintf(&b, "Title: %s: %s             Repo: %s\n", c.Key, symptom(c), repo)
	fmt.Fprintf(&b, "Suspect: %s (primitive %s), plus the playbook class row census.tsv %s\n", suspect, prim, c.SHA12)
	if c.Harness {
		fmt.Fprintf(&b, "Repro first: %s, then a red follower test (go test -run '^TestX$' ./oracle/xengine/... under the 4G scope)\n", repro)
	} else {
		fmt.Fprintf(&b, "Repro first: %s, then a red engine test (make test-one PKG=./engine/rules RUN='^TestX$', the 4G scope)\n", repro)
	}
	fmt.Fprintf(&b, "Evidence: %d games, %d decks, signatures [%s], first diff at %s (gorge %q, other %q), Forge log offset %d (%s)\n",
		len(games), len(decks), strings.Join(sigs, ", "), s.Field, clip(s.Gorge), clip(s.Other), s.Offset, s.Log)
	if c.Harness {
		b.WriteString("Corroboration: TODO(triager): the forge-shadow-1 record and the gorge decision it should map to\n")
		fmt.Fprintf(&b, "Acceptance: the repro replays clean; no census row is %s\n", prim)
	} else {
		b.WriteString("Corroboration: TODO(triager): XMage or Forge rule text for the expected behaviour (CR cite); if it supports gorge, this is not a gorge ticket\n")
		fmt.Fprintf(&b, "Acceptance: the repro replays clean; the class census rows for %s are clean\n", prim)
	}
	if len(others) == 0 {
		b.WriteString("Not in scope: other primitives in the census (none)\n")
	} else {
		fmt.Fprintf(&b, "Not in scope: other primitives in the census: %s\n", strings.Join(others, ", "))
	}
	fmt.Fprintf(&b, "\nGenerated by `xengine adjudicate -fshadow`. Class %s, score %s; cards: %s.\n\n## Signatures\n\n", c.SHA12, score(c.Score), strings.Join(sortedSet(names), ", "))
	for _, sg := range c.Signatures {
		fmt.Fprintf(&b, "- %s `%s`: %d game(s) x %d deck(s) x paper %s = %s\n", sg.SHA12, sg.Key, sg.Games, sg.Decks, score(sg.Paper), score(sg.Score))
		for i, f := range sg.Findings {
			if i == 3 {
				fmt.Fprintf(&b, "  - ... %d more\n", len(sg.Findings)-3)
				break
			}
			fmt.Fprintf(&b, "  - game %s seed %d offset %d, %s: gorge %q, other %q\n", f.Game, f.Seed, f.Offset, f.Field, clip(f.Gorge), clip(f.Other))
		}
	}
	return b.String()
}

func score(f float64) string { return fmt.Sprintf("%g", f) }

func uniqSorted(ss []string) []string {
	m := map[string]bool{}
	for _, s := range ss {
		m[s] = true
	}
	return sortedSet(m)
}

func sortedSet(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// fshadowFiles is the census's output: census.tsv (both rankings) and
// tickets/<class-sha12>.md per class, beside the three-way drafts.
func fshadowFiles(c *Census, r Ranker) map[string][]byte {
	var tsv bytes.Buffer
	tsv.WriteString("rank\tlist\tscore\tclass\tkey\tsignatures\tgames\n")
	files := map[string][]byte{}
	for _, l := range []struct {
		name    string
		classes []Class
	}{{"gorge", c.Classes}, {"harness", c.Harness}} {
		for i, cl := range l.classes {
			games := map[string]bool{}
			for _, s := range cl.Signatures {
				for _, f := range s.Findings {
					games[f.Game] = true
				}
			}
			fmt.Fprintf(&tsv, "%d\t%s\t%s\t%s\t%s\t%d\t%d\n", i+1, l.name, score(cl.Score), cl.SHA12, cl.Key, len(cl.Signatures), len(games))
			files[filepath.Join("tickets", cl.SHA12+".md")] = []byte(fshadowBrief(cl, c, r))
		}
	}
	files["census.tsv"] = tsv.Bytes()
	return files
}
