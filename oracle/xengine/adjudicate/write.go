func sha12(s string) string {
	h := sha256.Sum256([]byte(s))
	return hex.EncodeToString(h[:])[:12]
}

// valueClip bounds a quoted game-state value: a draft quotes short facts only.
const valueClip = 300

func clip(s string) string {
	if len(s) <= valueClip {
		return s
	}
	return s[:valueClip] + "..."
}

// Write puts the adjudication under out (outside the repository): findings.jsonl
// (one Row per adjudicated item, no values), notes.md, patterns.tsv and
// tickets/<cluster-sha12>.md per draft. Nothing it writes is a verdict row or
// a ruling.
func Write(out string, res Result) error {
	if err := classify.RefuseRepoPath(out); err != nil {
		return err
	}
	var fj bytes.Buffer
	hist := map[string]int{}
	for _, r := range res.Rows {
		b, err := json.Marshal(r)
		if err != nil {
			return err
		}
		fj.Write(append(b, '\n'))
		hist[r.Pattern]++
	}
	var pat bytes.Buffer
	ps := make([]string, 0, len(hist))
	for p := range hist {
		ps = append(ps, p)
	}
	sort.Strings(ps)
	for _, p := range ps {
		fmt.Fprintf(&pat, "%s\t%d\n", p, hist[p])
	}
	var notes bytes.Buffer
	notes.WriteString("# adjudication notes\n\nNotes only: nothing here is a ruling or a verdict row.\n\n")
	for _, n := range res.Notes {
		fmt.Fprintf(&notes, "- %s\n", n)
	}
	files := map[string][]byte{"findings.jsonl": fj.Bytes(), "patterns.tsv": pat.Bytes(), "notes.md": notes.Bytes()}
	for _, c := range res.Drafts {
		files[filepath.Join("tickets", c.SHA12+".md")] = []byte(draft(c))
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if err := writeAtomic(filepath.Join(out, n), files[n]); err != nil {
			return err
		}
	}
	return nil
}

func writeAtomic(path string, b []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// draft is a ticket draft in the shape of `oraclediff tickets` briefs: a
// markdown file whose first line is the title.
func draft(c Cluster) string {
	var b strings.Builder
	card := c.Card
	if card == "" {
		card = "(no card named by the diverging step)"
	}
	fmt.Fprintf(&b, "# gorge: %s differs from XMage and Forge at `%s` (%d finding(s))\n\n", card, c.FieldClass, len(c.Findings))
	b.WriteString("Generated by `xengine adjudicate` (DESIGN xengine section 4.1). In every finding below XMage and Forge agree with each other and both differ from gorge (pattern FX|G, label gorge_suspect). That is a candidate, not a ruling: the triager corroborates it against the Oracle text and the CR before filing.\n\n")
	b.WriteString("## Cluster\n\n")
	fmt.Fprintf(&b, "- card: %s\n- field class: `%s`\n- findings: %d\n- cluster: %s\n\n", card, c.FieldClass, len(c.Findings), c.SHA12)
	for _, f := range c.Findings {
		fmt.Fprintf(&b, "- `%s` (%d step(s), first difference `%s` at `%s`)\n", f.ID, f.Steps, f.Diverging.Field, f.Diverging.Checkpoint)
	}
	s := c.Smallest
	fmt.Fprintf(&b, "\n## Smallest repro\n\n`%s`, %d step(s).\n\nFirst difference at `%s`, field `%s` (short game-state facts only):\n\n- gorge: `%s`\n- xmage: `%s`\n- forge: `%s`\n\n", s.ID, s.Steps, s.Diverging.Checkpoint, s.Diverging.Field, clip(s.Diverging.Gorge), clip(s.XVal), clip(s.FVal))
	for _, r := range []struct{ engine, path string }{{"xmage", s.XRepro}, {"forge", s.FRepro}} {
		fmt.Fprintf(&b, "### %s repro commands\n\n", r.engine)
		if cmds := reproCommands(r.path); cmds != "" {
			fmt.Fprintf(&b, "From `%s`:\n\n%s\n", r.path, cmds)
		} else {
			fmt.Fprintf(&b, "No REPRO.md found (%q).\n\n", r.path)
		}
	}
	b.WriteString("## Oracle text + CR\n\nTODO(triager): paste the card's Oracle text and the CR rule(s) that decide the first difference above, and say which engine they support, before filing. If they support gorge, this is not a gorge ticket.\n")
	return b.String()
}

// reproCommands is the fenced blocks of a REPRO.md, verbatim.
func reproCommands(path string) string {
	if path == "" {
		return ""
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	var out strings.Builder
	in := false
	for _, line := range strings.Split(string(raw), "\n") {
		if strings.HasPrefix(line, "```") {
			in = !in
			out.WriteString(line + "\n")
			if !in {
				out.WriteString("\n")
			}
			continue
		}
		if in {
			out.WriteString(line + "\n")
		}
	}
	return out.String()
}

// LedgerRow is one line of the opt-in ledger, the D1=C compact shape the Forge
// pass commits (cmd/oraclediff ledgerRow): our labels and field names, ids and
// refs. No snapshot value and no follower message is ever in it.
type LedgerRow struct {
	ID       string `json:"id"`
	Card     string `json:"card,omitempty"`
	ForgeRef string `json:"forge_ref,omitempty"`
	Pattern  string `json:"pattern"`
	Label    string `json:"label,omitempty"`
	GXField  string `json:"gx_field,omitempty"`
	GFField  string `json:"gf_field,omitempty"`
	FXField  string `json:"fx_field,omitempty"`
}

// WriteLedger writes the rows that carry a pattern a three-way table decides
// (not INCONSISTENT / F harness), sharded <a-z>.jsonl by card and sorted by
// id, under dir, which must be outside the repository: this tool never writes
// into it. forgeRef (FORGE_ORACLE_REF[:12]) is stamped on each row when given.
func WriteLedger(dir string, rows []Row, forgeRef string) error {
	if err := classify.RefuseRepoPath(dir); err != nil {
		return err
	}
	shards := map[string][]LedgerRow{}
	for _, r := range rows {
		if r.Label == "" {
			continue
		}
		s := compliance.Shard(r.Card)
		shards[s] = append(shards[s], LedgerRow{
			ID: r.ID, Card: r.Card, ForgeRef: forgeRef, Pattern: r.Pattern, Label: r.Label,
			GXField: r.GXField, GFField: r.GFField, FXField: r.FXField,
		})
	}
	names := make([]string, 0, len(shards))
	for s := range shards {
		names = append(names, s)
	}
	sort.Strings(names)
	for _, s := range names {
		rs := shards[s]
		sort.Slice(rs, func(i, j int) bool { return rs[i].ID < rs[j].ID })
		var b bytes.Buffer
		enc := json.NewEncoder(&b)
		enc.SetEscapeHTML(false)
		for _, r := range rs {
			if err := enc.Encode(r); err != nil {
				return err
			}
		}
		if err := writeAtomic(filepath.Join(dir, s+".jsonl"), b.Bytes()); err != nil {
			return err
		}
	}
	return nil
}
